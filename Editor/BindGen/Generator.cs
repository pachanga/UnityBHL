using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

internal class Generator
{
  readonly Config conf;
  readonly ICsParser parser;
  readonly CsDecls decls = new CsDecls();
  //NOTE: with the declarations file binding it, the output is split by them
  readonly List<(MethodDecl m, string decl_file)> funcs = new List<(MethodDecl, string)>();
  readonly List<string> imports = new List<string>();

  static readonly string[] header_usings = { "System", "System.Collections", "System.Collections.Generic", "bhl" };

  public int FuncsCount => funcs.Count;
  public int ClassesCount => decls.Classes.Count;

  //NOTE: the max of functions and classes in one output file, as metagen_bhl_bind slices its output:
  //      IL2CPP has troubles with too large files and methods
  const int SliceSize = 20;
  public const string MainFile = "register.cs";
  public const string Header = "//THIS FILE IS GENERATED by UnityBHL bindgen, do not edit";

  public Generator(Config conf, ICsParser parser)
  {
    this.conf = conf;
    this.parser = parser;
  }

  //NOTE: generates and writes the output, returns the summary and whether a file was written or deleted
  public (string summary, bool changed) Run()
  {
    Collect();
    var files = Emit();

    Directory.CreateDirectory(conf.result_dir);
    int written = files.Count(kv => WriteIfChanged(Path.Combine(conf.result_dir, kv.Key), kv.Value));
    //NOTE: only the generated files, recognized by the header, anything else in the dir is left as is
    int deleted = 0;
    foreach(var file in Directory.GetFiles(conf.result_dir, "*.cs"))
    {
      if(files.ContainsKey(Path.GetFileName(file)) || File.ReadLines(file).FirstOrDefault() != Header)
        continue;
      File.Delete(file);
      ++deleted;
    }
    return ($"bindgen: {FuncsCount} funcs, {ClassesCount} classes -> {conf.result_dir} ({files.Count} files, {written} written, {deleted} deleted)",
      written + deleted > 0);
  }

  //NOTE: an unchanged output isn't touched, so neither Unity nor the BHL compiler rebuild anything
  static bool WriteIfChanged(string path, string content)
  {
    if(File.Exists(path) && File.ReadAllText(path) == content)
      return false;
    File.WriteAllText(path, content);
    return true;
  }

  void Collect()
  {
    foreach(var file in conf.DeclFiles)
      parser.ParseDecls(file, File.ReadAllText(file), decls);

    var types = new HashSet<string>(decls.Binds.Select(b => b.Type));
    foreach(var c in decls.Classes.Where(c => c.MemberRefs.Count > 0))
    {
      types.Add(c.NativeType.Name);
      types.UnionWith(c.MemberRefs.Where(r => r.Type != null).Select(r => r.Type));
    }
    foreach(var file in conf.SourceFiles)
    {
      var src = File.ReadAllText(file);
      //NOTE: parsing only the files which may declare enums or bound types
      if(!src.Contains("enum ") && !types.Any(t => src.Contains("class " + t) || src.Contains("struct " + t) || src.Contains("interface " + t)))
        continue;
      parser.ParseSource(file, src, types, decls);
    }

    var seen = new HashSet<string>();
    foreach(var b in decls.Binds)
    {
      if(!seen.Add(b.Name))
        throw new GenException(b.Pos, $"'{b.Name}' is bound twice");
      if(!decls.Methods.TryGetValue((b.Type, b.Name), out var found) || !found[0].IsStatic)
        throw new GenException(b.Pos, $"static method '{b.Type}.{b.Name}' is not found in the sources");
      if(found.Count > 1)
        throw new GenException(found[1].Pos, $"'{b.Type}.{b.Name}' is overloaded, BHL has no overloads");
      AddFunc(found[0], b.Pos.File);
    }

    foreach(var c in decls.Customs)
    {
      if(!seen.Add(c.Name))
        throw new GenException(c.Pos, $"'{c.Name}' is bound twice");
      AddFunc(c, c.Pos.File);
    }

    var seen_classes = new HashSet<string>();
    foreach(var c in decls.Classes)
    {
      if(!seen_classes.Add(c.Name))
        throw new GenException(c.Pos, $"class '{c.Name}' is bound twice");
      AddImports(c.Usings);
      foreach(var r in c.MemberRefs)
        AddMember(c, r);
      foreach(var m in c.Methods)
      {
        if(m.IsCustom || m.IsCoroutine)
          throw new GenException(m.Pos, "custom and coroutine class methods are not supported yet");
        if(m.SelfArgType == null)
          continue;
        //NOTE: as metagen_bhl_bind binds a method without its own native prefix
        var name = c.Name + "_" + m.Name;
        if(!decls.Methods.TryGetValue((m.SelfArgType, name), out var found) || !found[0].IsStatic)
          throw new GenException(m.Pos, $"static method '{m.SelfArgType}.{name}' is not found in the sources");
        m.Target = found[0].Target;
        AddImports(found[0].Usings);
      }
    }
  }

  //NOTE: a member of the native type itself, or a static <Type>.<Class>_<Method>(self, ..) of another one
  void AddMember(ClassDecl c, MemberRef r)
  {
    var native = c.NativeType.Name;
    if(r.Type == null || r.Type == native)
    {
      if(decls.Fields.TryGetValue((native, r.Name), out var field))
      {
        c.Fields.Add(field);
        AddImports(field.Usings);
        return;
      }
      if(!decls.Methods.TryGetValue((native, r.Name), out var found))
        throw new GenException(r.Pos, $"member '{native}.{r.Name}' is not found in the sources");
      if(found.Count > 1)
        throw new GenException(found[1].Pos, $"'{native}.{r.Name}' is overloaded, BHL has no overloads");
      if(found[0].IsStatic)
        throw new GenException(r.Pos, $"static '{native}.{r.Name}' is not supported yet");
      c.Methods.Add(found[0]);
      AddImports(found[0].Usings);
      return;
    }

    var prefix = c.Name + "_";
    if(!r.Name.StartsWith(prefix))
      throw new GenException(r.Pos, $"'{r.Type}.{r.Name}' is expected to be named {prefix}<Method>");
    if(!decls.Methods.TryGetValue((r.Type, r.Name), out var self_arg) || !self_arg[0].IsStatic)
      throw new GenException(r.Pos, $"static method '{r.Type}.{r.Name}' is not found in the sources");
    if(self_arg.Count > 1)
      throw new GenException(self_arg[1].Pos, $"'{r.Type}.{r.Name}' is overloaded, BHL has no overloads");
    var m = self_arg[0];
    if(m.Params.Count == 0 || m.Params[0].Type.Name != native)
      throw new GenException(m.Pos, $"the first parameter of '{r.Type}.{r.Name}' is expected to be {native} self");
    //NOTE: a copy, the same method may be bound by other declarations
    c.Methods.Add(new MethodDecl {
      Name = r.Name.Substring(prefix.Length),
      SelfArgType = r.Type,
      ReturnType = m.ReturnType,
      Params = m.Params.Skip(1).ToList(),
      Usings = m.Usings,
      Pos = m.Pos,
    });
  }

  void AddImports(List<string> usings)
  {
    foreach(var u in usings)
    {
      if(!header_usings.Contains(u) && !imports.Contains(u))
        imports.Add(u);
    }
  }

  void AddFunc(MethodDecl m, string decl_file)
  {
    funcs.Add((m, decl_file));
    //NOTE: the signatures are written as in their files, so the output imports their usings
    AddImports(m.Usings);
  }

  enum Kind
  {
    Void,
    Builtin,
    Any,
    Enum,
    Obj,
    CustomRw,
    Tuple,
    //NOTE: IList<T>, Items[0] is T
    Arr,
    //NOTE: IList, BHL []any
    AnyArr,
    //NOTE: Action<..> or Func<..>, Items are the args
    Func,
  }

  class TypeRef
  {
    public Kind Kind;
    //NOTE: the C# type as written in the source (a keyword for builtins)
    public string Cs;
    public string Bhl;
    public List<TypeRef> Items;
    //NOTE: the name of the native list type of an Arr, named as metagen_bhl_bind does
    public string Proxy;
    //NOTE: the field holding the native list type of an Arr
    public string ProxyField;
    //NOTE: the return type of a Func
    public TypeRef Ret;
    //NOTE: a coroutine Func
    public bool IsCoro;

    //NOTE: the type of a C# variable holding the value
    public string Native => Kind == Kind.Any ? "bhl.Val" : Cs;

    public bool IsFloat => Cs == "float" || Cs == "double";
  }

  static readonly Dictionary<string, string> builtins = new Dictionary<string, string>
  {
    {"float", "float"}, {"double", "float"},
    {"int", "int"}, {"uint", "int"}, {"short", "int"}, {"ushort", "int"}, {"sbyte", "int"}, {"byte", "int"},
    {"long", "int"}, {"ulong", "int"},
    {"string", "string"}, {"bool", "bool"},
  };

  //NOTE: meta names of builtins, the native list types are named after them
  static readonly Dictionary<string, string> meta_names = new Dictionary<string, string>
  {
    {"float", "float"}, {"double", "double"},
    {"int", "int32"}, {"uint", "uint32"}, {"short", "int16"}, {"ushort", "uint16"}, {"sbyte", "int8"}, {"byte", "uint8"},
    {"long", "int64"}, {"ulong", "uint64"},
    {"string", "string"}, {"bool", "bool"},
  };

  static readonly TypeRef void_type = new TypeRef { Kind = Kind.Void, Cs = "void", Bhl = "void" };

  static readonly TypeDecl no_result = new TypeDecl();

  //NOTE: the result type of a BhlTask form: no_result for BhlTask, BhlFinallyTask, T for BhlTask<T>,
  //      BhlFinallyTask<T>, null if it's not one
  static TypeDecl TaskResult(TypeDecl t)
  {
    if(t.Name != "BhlTask" && t.Name != "BhlFinallyTask")
      return null;
    if(t.GenericArgs == null)
      return no_result;
    return t.GenericArgs.Count == 1 ? t.GenericArgs[0] : null;
  }

  TypeRef Resolve(TypeDecl t, bool is_return, bool is_coro = false)
  {
    if(t.Keyword != null)
    {
      if(t.Keyword == "void" && is_return)
        return new TypeRef { Kind = Kind.Void, Cs = t.Keyword, Bhl = "void" };
      if(builtins.TryGetValue(t.Keyword, out var bhl))
        return new TypeRef { Kind = Kind.Builtin, Cs = t.Keyword, Bhl = bhl };
    }
    else if(t.TupleItems != null && is_return)
    {
      return new TypeRef { Kind = Kind.Tuple, Cs = t.Text, Items = t.TupleItems.Select(i => Resolve(i, false)).ToList() };
    }
    else if(t.Name == "IList" && t.GenericArgs == null)
    {
      return new TypeRef { Kind = Kind.AnyArr, Cs = t.Text, Bhl = "any" };
    }
    else if(t.Name == "IList" && t.GenericArgs.Count == 1)
    {
      var item = Resolve(t.GenericArgs[0], false);
      if(item.Kind != Kind.Any && item.Kind != Kind.Arr && item.Kind != Kind.AnyArr)
        return new TypeRef { Kind = Kind.Arr, Cs = t.Text, Items = new List<TypeRef> { item },
          Proxy = "List_" + (item.Kind == Kind.Builtin ? meta_names[item.Cs] : item.Bhl),
          ProxyField = $"{conf.register_class}.t_List_" + (item.Kind == Kind.Builtin ? meta_names[item.Cs] : item.Bhl) };
    }
    else if(t.Name == "Action" || (t.Name == "Func" && t.GenericArgs != null))
    {
      var sig = (t.GenericArgs ?? new List<TypeDecl>()).Select(a => Resolve(a, false)).ToList();
      var ret = void_type;
      if(t.Name == "Func")
      {
        ret = sig[sig.Count - 1];
        sig.RemoveAt(sig.Count - 1);
      }
      return new TypeRef { Kind = Kind.Func, Cs = "VM.FuncPtr", Items = sig, Ret = ret, IsCoro = is_coro };
    }
    else if(t.Name != null && t.GenericArgs == null)
    {
      var kind = t.Name == "Val" ? Kind.Any : conf.custom_rw.Contains(t.Name) ? Kind.CustomRw : decls.Enums.Contains(t.Name) ? Kind.Enum : Kind.Obj;
      return new TypeRef { Kind = kind, Cs = t.Text, Bhl = kind == Kind.Any ? "any" : t.Name };
    }
    throw new GenException(t.Pos, $"type '{t.Text}' is not supported");
  }

  static string TypeRefCode(TypeRef t)
  {
    if(t.Kind == Kind.Tuple)
      return "types.TTuple(" + string.Join(",", t.Items.Select(TypeRefCode)) + ")";
    if(t.Kind == Kind.Arr)
      return "types.TArr(" + TypeRefCode(t.Items[0]) + ")";
    if(t.Kind == Kind.AnyArr)
      return "types.TArr(types.T(\"any\"))";
    if(t.Kind == Kind.Func)
      return $"types.TFunc({(t.IsCoro ? "true" : "false")}, {TypeRefCode(t.Ret)}" + string.Concat(t.Items.Select(i => ", " + TypeRefCode(i))) + ")";
    return $"types.T(\"{t.Bhl}\")";
  }

  static string Val2Native(TypeRef t, string val, string native)
  {
    switch(t.Kind)
    {
      case Kind.Builtin:
        switch(t.Cs)
        {
          case "double": return $"{native} = {val}.num;";
          case "string": return $"{native} = {val}.str;";
          case "bool": return $"{native} = {val}.bval;";
          default: return $"{native} = ({t.Cs}){val}.num;";
        }
      case Kind.Any:
        return $"{native} = {val}; {native}._refc?.Retain();";
      case Kind.Enum:
        return $"{native} = ({t.Cs})((int){val}.num);";
      case Kind.CustomRw:
        return $"{val}.Decode(ref {native});";
      //NOTE: a BHL array is wrapped, a native list is passed as is
      case Kind.Arr:
        return $"if({val}.obj is ValList vl) {native} = ValList<{t.Items[0].Cs}>.New(vl, ((NativeListTypeSymbol<{t.Items[0].Cs}>){t.ProxyField}).Val2Native); " +
          $"else {native} = ({t.Cs}){val}.obj; {val}._refc?.Retain();";
      case Kind.AnyArr:
        return $"{native} = (IList){val}.obj; {val}._refc?.Retain();";
      case Kind.Func:
        return $"{native} = (VM.FuncPtr){val}.obj; {native}.Retain();";
      default:
        return $"{native} = ({t.Cs}){val}.obj;";
    }
  }

  static string Native2Val(TypeRef t, string native, string val)
  {
    switch(t.Kind)
    {
      case Kind.Builtin:
        if(t.IsFloat)
          return $"{val}.SetFlt({native});";
        if(t.Cs == "string")
          return $"{val}.SetStr({native});";
        if(t.Cs == "bool")
          return $"{val}.SetBool({native});";
        return $"{val}.SetInt({native});";
      case Kind.Any:
      case Kind.Func:
        return $"{val}.SetObj({native}, Types.Any);";
      case Kind.Enum:
        return $"{val}.SetInt((int){native});";
      case Kind.CustomRw:
        return $"{val}.Encode({native});";
      case Kind.Arr:
        return $"{val}.SetObj({native}, {t.ProxyField});";
      default:
        return $"{val}.SetObjNoRefc({native}, Types_{t.Bhl}.Value);";
    }
  }

  //NOTE: pushes the native return value(s) onto the stack
  static void ReturnVal(StringBuilder sb, TypeRef t, string var, string indent)
  {
    if(t.Kind == Kind.Tuple)
    {
      //NOTE: items are pushed from the last one
      for(int i = t.Items.Count; i-- > 0;)
        sb.Append($"{indent}{{ var dv{i} = new Val(); {Native2Val(t.Items[i], var + ".Item" + (i + 1), "dv" + i)} exec.stack.Push(dv{i}); }}\n");
    }
    else if(t.Kind == Kind.Any)
      sb.Append($"{indent}exec.stack.Push({var});\n");
    else if(t.Kind == Kind.Builtin)
    {
      if(t.IsFloat)
        sb.Append($"{indent}exec.stack.Push((double){var});\n");
      else if(t.Cs == "string" || t.Cs == "bool")
        sb.Append($"{indent}exec.stack.Push(({t.Cs}){var});\n");
      else
        sb.Append($"{indent}exec.stack.Push(Val.NewInt((double){var}));\n");
    }
    else
      sb.Append($"{indent}{{ var dv = new Val(); {Native2Val(t, var, "dv")} exec.stack.Push(dv); }}\n");
  }

  static string DisposeArg(TypeRef t, string v)
  {
    switch(t.Kind)
    {
      case Kind.Any:
        return $"{v}._refc?.Release(); {v} = default;";
      case Kind.Arr:
      case Kind.AnyArr:
        return $"{{ if({v} is IRefcounted rfc) rfc.Release(); {v} = default; }}";
      case Kind.Func:
        return $"{v}?.Release(); {v} = default;";
      default:
        return null;
    }
  }

  class Func
  {
    public MethodDecl Decl;
    public List<(string name, TypeRef type, string def)> Args;
    public TypeRef Ret;
    //NOTE: returns a BhlTask form (BitGames.BhlTask of UnityBHL), bound as a coroutine, Ret is its result
    public bool IsTask;

    public bool IsCoroutine => Decl.IsCoroutine || IsTask;
    public string Name => Decl.Name;
    public string Partial => "Script_" + Decl.Name;
    public bool HasDisposableArgs => Args.Any(a => DisposeArg(a.type, "") != null);
    //NOTE: a builtin or any returned by a non coroutine is pushed directly, others by the generated ReturnValue(..)
    public bool HasReturnValue => Ret.Kind != Kind.Void && (IsCoroutine || (Ret.Kind != Kind.Builtin && Ret.Kind != Kind.Any));
    public List<TypeRef> RetItems => Ret.Kind == Kind.Void ? new List<TypeRef>() : Ret.Kind == Kind.Tuple ? Ret.Items : new List<TypeRef> { Ret };
  }

  Func ResolveFunc(MethodDecl m)
  {
    foreach(var p in m.Params)
    {
      if(p.Modifiers != "")
        throw new GenException(p.Pos, $"parameter modifier '{p.Modifiers}' is not supported");
    }
    if(m.IsCoroutine && !m.IsCustom)
      throw new GenException(m.Pos, $"a coroutine is bound only as a custom one, declare '{m.Name}' in a [BhlCustom] interface");
    var task_result = TaskResult(m.ReturnType);
    var f = new Func {
      Decl = m,
      Args = m.Params.Select(p => (name: p.Name, type: Resolve(p.Type, false, p.IsCoroutine), def: p.Default)).ToList(),
      IsTask = task_result != null,
      Ret = task_result == null ? Resolve(m.ReturnType, true) : task_result == no_result ? void_type : Resolve(task_result, true),
    };
    if(f.IsTask)
    {
      if(m.IsCustom)
        throw new GenException(m.ReturnType.Pos, "a custom binding can't return a BhlTask, bind the method directly");
      //NOTE: the coroutine outlives the call of the method, the args would be released while the task still uses them
      foreach(var a in f.Args.Where(a => DisposeArg(a.type, "") != null))
        throw new GenException(m.Params.First(p => p.Name == a.name).Pos, $"a BhlTask coroutine can't take '{a.type.Cs}' yet: the arg would be released before the task completes");
    }
    foreach(var p in m.Params.Where(p => p.IsCoroutine))
    {
      if(f.Args.First(a => a.name == p.Name).type.Kind != Kind.Func)
        throw new GenException(p.Pos, "[BhlCoroutine] is expected on a func-typed parameter");
    }
    if(f.RetItems.Any(i => i.Kind == Kind.AnyArr || i.Kind == Kind.Func))
      throw new GenException(m.ReturnType.Pos, $"returning '{m.ReturnType.Text}' is not supported");
    return f;
  }

  class Class
  {
    public ClassDecl Decl;
    public TypeRef Self;
    public List<(FieldDecl decl, TypeRef type)> Fields;
    public List<Func> Methods;
  }

  Class ResolveClass(ClassDecl c)
  {
    var cl = new Class {
      Decl = c,
      Self = new TypeRef { Kind = Kind.Obj, Cs = c.NativeType.Text, Bhl = c.Name },
      Fields = c.Fields.Select(f => (f, Resolve(f.Type, false))).ToList(),
      Methods = c.Methods.Select(ResolveFunc).ToList(),
    };
    foreach(var f in cl.Fields)
    {
      if(f.type.Kind == Kind.Arr || f.type.Kind == Kind.AnyArr || f.type.Kind == Kind.Func)
        throw new GenException(f.decl.Pos, $"a field of type '{f.decl.Type.Text}' is not supported");
    }
    return cl;
  }

  //NOTE: a part of the output: the functions and classes of one declarations file, or a slice of them
  class Slice
  {
    public string Name;
    public List<Class> Classes = new List<Class>();
    public List<Func> Funcs = new List<Func>();
    public int Count => Classes.Count + Funcs.Count;
  }

  //NOTE: the output files by their names
  Dictionary<string, string> Emit()
  {
    var resolved = funcs.Select(f => (f: ResolveFunc(f.m), f.decl_file)).ToList();
    var classes = decls.Classes.Select(ResolveClass).ToList();
    var all_funcs = resolved.Select(r => r.f).Concat(classes.SelectMany(c => c.Methods)).ToList();
    //NOTE: the native list types of the array args and returns, by name in the order of use
    var proxies = new Dictionary<string, TypeRef>();
    foreach(var f in all_funcs)
    {
      foreach(var t in f.Args.Select(a => a.type).Concat(f.RetItems))
      {
        if(t.Kind == Kind.Arr && !proxies.ContainsKey(t.Proxy))
          proxies.Add(t.Proxy, t.Items[0]);
      }
    }

    //NOTE: the files the output is made of, the Unity editor regenerates it when one of them changes
    var deps = conf.DeclFiles
      .Concat(all_funcs.Select(f => f.Decl.Pos.File))
      .Concat(classes.SelectMany(c => c.Decl.Fields.Select(f => f.Pos.File)))
      .Select(f => Path.GetRelativePath(conf.Dir, f).Replace('\\', '/'))
      .Distinct()
      .OrderBy(f => f, System.StringComparer.Ordinal);

    var slices = MakeSlices(classes, resolved);
    var files = new Dictionary<string, string>();
    foreach(var slice in slices)
      files.Add(slice.Name + ".cs", EmitSlice(slice));

    var sb = new StringBuilder();
    sb.Append(Header + "\n");
    foreach(var d in deps)
      sb.Append($"//dep: {d}\n");
    EmitFileBegin(sb);
    if(proxies.Count > 0)
    {
      sb.Append("#if !BHL_FRONT\n");
      foreach(var name in proxies.Keys)
        sb.Append($"internal static IType t_{name};\n");
      sb.Append("#endif\n\n");
    }

    //NOTE: as BHL_AutoBindings of metagen_bhl_bind: all RegisterBegin(..) go before all RegisterEnd(..),
    //      which set up the classes once all the types are defined
    sb.Append("public static void RegisterBegin(Types types)\n{\n");
    foreach(var kv in proxies)
      EmitProxy(sb, kv.Key, kv.Value);
    foreach(var slice in slices)
      sb.Append($"  Register_{slice.Name}(types);\n");
    sb.Append("}\n\n");

    sb.Append("public static void RegisterEnd(Types types)\n{\n");
    foreach(var c in classes)
    {
      sb.Append("#if !BHL_FRONT\n");
      sb.Append($"  Types_{c.Decl.Name}.Value = SetupType(types, \"{c.Decl.Name}\");\n");
      sb.Append("#else\n");
      sb.Append($"  types.SetupType(\"{c.Decl.Name}\");\n");
      sb.Append("#endif\n");
    }
    sb.Append("}\n\n");

    if(classes.Count > 0)
    {
      sb.Append("#if !BHL_FRONT\n");
      sb.Append("static IType SetupType(Types types, string name)\n{\n");
      sb.Append("  var tmp = types.T(name).Get();\n");
      sb.Append("  if(tmp == null)\n    throw new System.Exception(\"Type '\" + name + \"' not resolved\");\n");
      sb.Append("  if(tmp is ClassSymbolNative csn)\n    csn.Setup();\n");
      sb.Append("  return tmp;\n}\n");
      sb.Append("#endif\n\n");
    }
    sb.Append("}\n\n");

    if(classes.Count > 0)
    {
      //NOTE: the same holders as metagen_bhl_bind declares, the code it generates refers to them
      sb.Append("#if !BHL_FRONT\n");
      foreach(var c in classes)
        sb.Append($"static public class Types_{c.Decl.Name} {{\n  static public IType Value;\n}}\n");
      sb.Append("#endif\n\n");
    }
    sb.Append("}\n");
    files.Add(MainFile, sb.ToString());
    return files;
  }

  //NOTE: by declarations file in the order of the files, split into slices of SliceSize
  static List<Slice> MakeSlices(List<Class> classes, List<(Func f, string decl_file)> funcs)
  {
    var by_file = new SortedDictionary<string, Slice>(System.StringComparer.Ordinal);
    Slice Of(string file)
    {
      if(!by_file.TryGetValue(file, out var s))
        by_file[file] = s = new Slice();
      return s;
    }
    foreach(var c in classes)
      Of(c.Decl.Pos.File).Classes.Add(c);
    foreach(var (f, file) in funcs)
      Of(file).Funcs.Add(f);

    var slices = new List<Slice>();
    var names = new Dictionary<string, string>();
    foreach(var kv in by_file)
    {
      var name = System.Text.RegularExpressions.Regex.Replace(Path.GetFileNameWithoutExtension(kv.Key), @"\W", "_");
      if(names.TryGetValue(name, out var other))
        throw new GenException($"declarations files '{other}' and '{kv.Key}' have the same name, their outputs would clash");
      names.Add(name, kv.Key);

      var all = kv.Value;
      int count = (all.Count + SliceSize - 1) / SliceSize;
      for(int i = 0; i < count; ++i)
      {
        var slice = new Slice { Name = count == 1 ? name : $"{name}_{i}" };
        //NOTE: classes first, as in the declarations
        var units = all.Classes.Cast<object>().Concat(all.Funcs).Skip(i * SliceSize).Take(SliceSize);
        foreach(var u in units)
        {
          if(u is Class c)
            slice.Classes.Add(c);
          else
            slice.Funcs.Add((Func)u);
        }
        slices.Add(slice);
      }
    }
    return slices;
  }

  void EmitFileBegin(StringBuilder sb)
  {
    sb.Append("#pragma warning disable CS0162\n");
    sb.Append("#pragma warning disable UDR0001\n\n");
    foreach(var u in header_usings)
      sb.Append($"using {u};\n");
    sb.Append("#if !BHL_FRONT\n");
    foreach(var imp in conf.imports.Concat(imports).Except(header_usings).Distinct())
      sb.Append($"using {imp};\n");
    sb.Append("#endif\n");
    sb.Append("using Types = bhl.Types;\n\n");
    sb.Append($"namespace {conf.@namespace} {{\n\n");
    sb.Append($"static public partial class {conf.register_class} {{\n\n");
  }

  string EmitSlice(Slice slice)
  {
    var sb = new StringBuilder();
    sb.Append(Header + "\n");
    EmitFileBegin(sb);
    sb.Append($"public static void Register_{slice.Name}(Types types)\n{{\n");
    foreach(var c in slice.Classes)
      EmitClass(sb, c);
    foreach(var f in slice.Funcs)
      EmitFunc(sb, f, "fn_" + f.Name, "types.ns", f.Decl.IsCustom ? null : $"{f.Decl.Target}.{f.Name}", null, false);
    sb.Append("}\n\n}\n\n");

    //NOTE: the generated parts of the hand written Script_<Name> of the custom bindings
    var customs = slice.Funcs.Where(f => f.Decl.IsCustom).ToList();
    if(customs.Count > 0)
    {
      sb.Append("#if !BHL_FRONT\n\n");
      foreach(var f in customs)
        EmitPartial(sb, f);
      sb.Append("#endif\n\n");
    }
    sb.Append("}\n");
    return sb.ToString();
  }

  void EmitClass(StringBuilder sb, Class c)
  {
    var name = c.Decl.Name;
    var native = c.Self.Cs;
    sb.Append("  {\n");
    if(c.Decl.New)
    {
      sb.Append($"    static void ctor_{name}(VM.ExecState exec, ref Val v, IType type)\n    {{\n");
      sb.Append("    #if !BHL_FRONT\n");
      sb.Append($"      var o = new {native}();\n");
      sb.Append("      v.SetObjNoRefc(o, type);\n");
      sb.Append("    #endif\n    }\n\n");
    }
    sb.Append($"    var cl = new ClassSymbolNative(new Origin(), \"{name}\",\n");
    sb.Append(c.Decl.Parent != null ? $"      types.T(\"{c.Decl.Parent}\"),\n" : "      new ProxyType(),\n");
    sb.Append("      proxy_implements: null,\n");
    sb.Append($"      creator: {(c.Decl.New ? "ctor_" + name : "null")}\n");
    sb.Append("      #if !BHL_FRONT\n");
    sb.Append($"      , native_type: typeof({native})\n");
    sb.Append("      #endif\n");
    sb.Append("    );\n");
    sb.Append("    types.ns.Define(cl);\n\n");

    foreach(var (f, t) in c.Fields)
    {
      var member = "f." + (f.Native ?? f.Name);
      sb.Append("    {\n");
      if(f.Get)
      {
        sb.Append($"      static void get_{name}_{f.Name}(VM.ExecState exec, Val ctx, ref Val v, FieldSymbol fld)\n      {{\n");
        sb.Append("      #if !BHL_FRONT\n");
        sb.Append($"        var f = ({native})ctx.obj;\n");
        sb.Append($"        {Native2Val(t, member, "v")}\n");
        sb.Append("      #endif\n      }\n");
      }
      if(f.Set)
      {
        sb.Append($"      static void set_{name}_{f.Name}(VM.ExecState exec, ref Val ctx, Val v, FieldSymbol fld)\n      {{\n");
        sb.Append("      #if !BHL_FRONT\n");
        sb.Append($"        var f = ({native})ctx.obj;\n");
        //NOTE: Decode(..) needs a variable, not a property
        if(t.Kind == Kind.CustomRw)
          sb.Append($"        {{ {t.Native} tmp = default; {Val2Native(t, "v", "tmp")} {member} = tmp; }}\n");
        else
          sb.Append($"        {Val2Native(t, "v", member)}\n");
        sb.Append("      #endif\n      }\n");
      }
      sb.Append($"      cl.Define(new FieldSymbol(new Origin(), \"{f.Name}\", {TypeRefCode(t)}, {(f.Get ? $"get_{name}_{f.Name}" : "null")}, {(f.Set ? $"set_{name}_{f.Name}" : "null")}));\n");
      sb.Append("    }\n");
    }

    foreach(var m in c.Methods)
    {
      bool self_arg = m.Decl.SelfArgType != null;
      var callee = self_arg ? $"{m.Decl.Target}.{name}_{m.Name}" : "__self." + (m.Decl.Native ?? m.Name);
      EmitFunc(sb, m, name + "_" + m.Name, "cl", callee, c.Self, self_arg);
    }
    sb.Append("  }\n");
  }

  //NOTE: the same native list type as metagen_bhl_bind defines, whichever registers first defines it
  static void EmitProxy(StringBuilder sb, string name, TypeRef item)
  {
    sb.Append($"  if(types.ns.Resolve(\"{name}\") == null)\n  {{\n");
    sb.Append("    var cl = new NativeListTypeSymbol<\n#if !BHL_FRONT\n");
    sb.Append($"    {item.Native}\n");
    sb.Append("#else\n    object\n#endif\n");
    sb.Append($"    >(new Origin(), \"{name}\",\n");
    sb.Append("#if !BHL_FRONT\n");
    sb.Append($"      (v) => {{ {item.Native} tmp = default; {Val2Native(item, "v", "tmp")} return tmp; }},\n");
    sb.Append($"      (itype, n) => {{ var v = new Val(); {Native2Val(item, "n", "v")} return v; }},\n");
    sb.Append("#else\n      null, null,\n#endif\n");
    sb.Append($"      {TypeRefCode(item)}\n    );\n");
    sb.Append("    cl.Setup();\n");
    sb.Append("    types.ns.Define(cl);\n  }\n");
    sb.Append("  #if !BHL_FRONT\n");
    sb.Append($"  t_{name} = (IType)types.ns.Resolve(\"{name}\");\n");
    sb.Append("  #endif\n");
  }

  //NOTE: args are popped in reverse order, a default one only when it was passed
  static void ReadArgs(StringBuilder sb, Func f, string prefix, string indent)
  {
    int defaults = f.Args.Count(a => a.def != null);
    int default_counter = 0;
    for(int i = f.Args.Count; i-- > 0;)
    {
      var a = f.Args[i];
      if(a.def != null)
      {
        ++default_counter;
        sb.Append($"{indent}if(!args_info.IsDefaultArgUsed({defaults - default_counter}))\n");
      }
      sb.Append($"{indent}{{ var dv = exec.stack.Pop(); {Val2Native(a.type, "dv", prefix + a.name)} dv._refc?.Release(); }}\n");
      if(a.def != null)
        sb.Append($"{indent}else\n{indent}  {prefix}{a.name} = {a.def};\n");
    }
  }

  //NOTE: callee is null for a custom one; self is the class of a method, passed to the callee first if self_arg
  void EmitFunc(StringBuilder sb, Func f, string local_fn, string scope, string callee, TypeRef self, bool self_arg)
  {
    sb.Append("  {\n");
    sb.Append("    #if !BHL_FRONT\n");
    sb.Append($"    static bhl.Coroutine {local_fn}(VM.ExecState exec, FuncArgsInfo args_info)\n    {{\n");
    if(f.Decl.IsCustom)
      EmitCustomCall(sb, f);
    else
      EmitDirectCall(sb, f, callee, self, self_arg);
    sb.Append("    }\n");
    sb.Append("    #endif\n\n");

    var attrib = f.IsCoroutine ? "FuncAttrib.Coro" : "FuncAttrib.None";
    sb.Append($"    var fn = new FuncSymbolNative(new Origin(), \"{f.Name}\", {attrib}, {TypeRefCode(f.Ret)}, {f.Args.Count(a => a.def != null)},\n");
    sb.Append("      #if !BHL_FRONT\n");
    sb.Append($"      {local_fn}\n");
    sb.Append("      #else\n      null\n      #endif\n");
    foreach(var a in f.Args)
      sb.Append($"      , new FuncArgSymbol(\"{a.name}\", {TypeRefCode(a.type)}, false)\n");
    sb.Append("    );\n");
    sb.Append($"    {scope}.Define(fn);\n");
    sb.Append("  }\n");
  }

  static void EmitDirectCall(StringBuilder sb, Func f, string callee, TypeRef self, bool self_arg)
  {
    if(self != null)
    {
      sb.Append("      ref var dv_self = ref exec.GetSelfRef();\n");
      sb.Append($"      {self.Native} __self = default;\n");
      sb.Append($"      {Val2Native(self, "dv_self", "__self")}\n");
    }
    foreach(var a in f.Args)
      sb.Append($"      {a.type.Native} __{a.name} = default;\n");
    ReadArgs(sb, f, "__", "      ");
    if(self != null)
      sb.Append("      exec.stack.Pop(); //pop self\n");
    var call_args = f.Args.Select(a => "__" + a.name);
    if(self_arg)
      call_args = call_args.Prepend("__self");
    if(f.IsTask)
    {
      EmitTaskCall(sb, f, $"{callee}({string.Join(", ", call_args)})", self != null);
      return;
    }
    sb.Append("      ");
    if(f.Ret.Kind != Kind.Void)
      sb.Append("var return_val = ");
    sb.Append($"{callee}({string.Join(", ", call_args)});\n");
    if(self != null)
      sb.Append("      dv_self._refc?.Release();\n");
    if(f.Ret.Kind != Kind.Void)
      ReturnVal(sb, f.Ret, "return_val", "      ");
    foreach(var a in f.Args)
    {
      var dispose = DisposeArg(a.type, "__" + a.name);
      if(dispose != null)
        sb.Append($"      {dispose}\n");
    }
    sb.Append("      return null;\n");
  }

  //NOTE: as metagen_bhl_bind binds a direct @bhl_coroutine: the scope makes the task live as long as the call,
  //      the result is pushed when the task completes
  static void EmitTaskCall(StringBuilder sb, Func f, string call, bool has_self)
  {
    sb.Append("      var scope = global::BitGames.BHL.BhlTaskScope.Enter();\n");
    sb.Append("      try\n      {\n");
    sb.Append($"        var task = {call};\n");
    if(has_self)
      sb.Append("        dv_self._refc?.Release();\n");
    sb.Append("        return global::BitGames.BHL.BhlTaskCoroutine.New(exec, scope, task");
    if(f.Ret.Kind != Kind.Void)
    {
      sb.Append(", static (exec, return_val) =>\n        {\n");
      ReturnVal(sb, f.Ret, "return_val", "          ");
      sb.Append("        }");
    }
    sb.Append(");\n");
    sb.Append("      }\n      finally\n      {\n        scope.Exit();\n      }\n");
  }

  //NOTE: calls the hand written Script_<Name>, as metagen_bhl_bind does for @bhl_bind_type:custom
  static void EmitCustomCall(StringBuilder sb, Func f)
  {
    if(f.Decl.IsCoroutine)
    {
      sb.Append($"      var coro = CoroutinePool.New<{f.Partial}>(exec.vm);\n");
      sb.Append("      coro.Init(exec, args_info);\n");
      sb.Append("      return coro;\n");
      return;
    }

    var results = f.RetItems.Select((t, i) => $", out {t.Native} result{i}");
    if(f.Args.Count > 0)
    {
      sb.Append($"      var args = {f.Partial}.ReadArgs(exec, args_info);\n");
      sb.Append($"      {f.Partial}.Exec(exec, args{string.Concat(results)});\n");
      if(f.HasDisposableArgs)
        sb.Append("      args.Dispose();\n");
    }
    else
      sb.Append($"      {f.Partial}.Exec(exec{string.Concat(results)});\n");
    if(f.HasReturnValue)
      sb.Append($"      {f.Partial}.ReturnValue(exec{string.Concat(f.RetItems.Select((t, i) => $", result{i}"))});\n");
    else if(f.Ret.Kind != Kind.Void)
      ReturnVal(sb, f.Ret, "result0", "      ");
    sb.Append("      return null;\n");
  }

  static void EmitPartial(StringBuilder sb, Func f)
  {
    sb.Append($"public partial class {f.Partial}{(f.Decl.IsCoroutine ? " : bhl.Coroutine" : "")}\n{{\n");

    if(f.Args.Count > 0)
    {
      sb.Append($"  public struct Args{(f.HasDisposableArgs ? " : IDisposable" : "")}\n  {{\n");
      foreach(var a in f.Args)
        sb.Append($"    public {a.type.Native} {a.name};\n");
      if(f.HasDisposableArgs)
      {
        sb.Append("\n    public void Dispose()\n    {\n");
        foreach(var a in f.Args)
        {
          var dispose = DisposeArg(a.type, a.name);
          if(dispose != null)
            sb.Append($"      {dispose}\n");
        }
        sb.Append("    }\n");
      }
      sb.Append("  }\n\n");

      sb.Append("  static public Args ReadArgs(VM.ExecState exec, FuncArgsInfo args_info)\n  {\n");
      sb.Append("    var args = new Args();\n");
      ReadArgs(sb, f, "args.", "    ");
      sb.Append("    return args;\n  }\n\n");
    }

    if(f.HasReturnValue)
    {
      sb.Append($"  static public void ReturnValue(VM.ExecState exec{string.Concat(f.RetItems.Select((t, i) => $", {t.Native} v{i}"))})\n  {{\n");
      //NOTE: items are pushed from the last one
      for(int i = f.RetItems.Count; i-- > 0;)
        sb.Append($"    {{ var dv{i} = new Val(); {Native2Val(f.RetItems[i], "v" + i, "dv" + i)} exec.stack.Push(dv{i}); }}\n");
      sb.Append("  }\n\n");
    }

    if(f.Decl.IsCoroutine)
    {
      if(f.Args.Count > 0)
        sb.Append("  Args args;\n\n");
      sb.Append("  public void Init(VM.ExecState exec, FuncArgsInfo args_info)\n  {\n");
      if(f.Args.Count > 0)
        sb.Append("    args = ReadArgs(exec, args_info);\n");
      sb.Append("    Init(exec);\n  }\n\n");
      sb.Append("  public override void Tick(VM.ExecState exec)\n  {\n    Exec(exec);\n  }\n\n");
      sb.Append("  public override void Destruct(VM.ExecState exec)\n  {\n    Cleanup(exec);\n");
      if(f.HasDisposableArgs)
        sb.Append("    args.Dispose();\n");
      if(f.Args.Count > 0)
        sb.Append("    args = default;\n");
      sb.Append("  }\n");
    }

    sb.Append("}\n\n");
  }
