  static readonly TypeRef void_type = new TypeRef { Kind = Kind.Void, Cs = "void", Bhl = "void" };

  static readonly TypeDecl no_result = new TypeDecl();

  //NOTE: the result type of a BhlTask form: no_result for BhlTask, BhlFinallyTask, T for BhlTask<T>,
  //      BhlFinallyTask<T>, null if it's not one
  static TypeDecl TaskResult(TypeDecl t)
  {
    if(t.Name != "BhlTask" && t.Name != "BhlFinallyTask")
      return null;
    if(t.GenericArgs == null)
      return no_result;
    return t.GenericArgs.Count == 1 ? t.GenericArgs[0] : null;
  }

  //NOTE: is_field: a field may be a List<T> too, it's read as IList<T> and written by copying into the list
  //NOTE: the layout of a generated codec is the declaration's get/set properties, the native ones of the same names:
  //      the native type may be out of the sources (UnityEngine.Vector3); when it's in them, each of its non-private
  //      instance fields must be in the layout, else its value would be lost in the Val
  List<FieldDecl> CheckAutoCodec(ClassDecl c)
  {
    if(!c.CustomRW)
      throw new GenException(c.Pos, $"class '{c.Name}': AutoCodec is of a CustomRW one, CustomRW = true is expected too");
    var layout = c.Fields.Where(f => f.Get && f.Set && f.Native == null).ToList();
    if(layout.Count == 0)
      throw new GenException(c.Pos, $"class '{c.Name}': AutoCodec takes its layout from the {{ get; set; }} properties, there are none");
    if(layout.Count > codec_slots.Length)
      throw new GenException(layout[codec_slots.Length].Pos, $"class '{c.Name}': AutoCodec keeps at most {codec_slots.Length} properties in the Val, '{layout[codec_slots.Length].Name}' is one more");
    foreach(var f in layout)
    {
      if(!(f.Type.Keyword != null ? codec_keywords.Contains(f.Type.Keyword) : f.Type.GenericArgs == null && decls.Enums.Contains(f.Type.Name)))
        throw new GenException(f.Pos, $"class '{c.Name}': AutoCodec keeps bool, numbers and enums, '{f.Name}' is '{f.Type.Text}'");
      if(decls.Fields.TryGetValue((c.NativeType.Name, f.Name), out var native) && !native.Set)
        throw new GenException(f.Pos, $"class '{c.Name}': '{c.NativeType.Name}.{f.Name}' is read only, AutoCodec can't decode it");
    }
    foreach(var kv in decls.Fields.Where(kv => kv.Key.type == c.NativeType.Name && kv.Value.IsField))
    {
      if(!layout.Any(f => f.Name == kv.Key.name))
        throw new GenException(c.Pos, $"class '{c.Name}': the field '{c.NativeType.Name}.{kv.Key.name}' isn't in the AutoCodec layout, a {{ get; set; }} property, its value would be lost");
    }
    return layout;
  }

  //NOTE: as a project's hand written codec of a CustomRW type: Encode sets the type, ToVal makes a Val of it
  void EmitCodec(StringBuilder sb, ClassDecl c)
  {
    var cs = c.NativeType.Text;
    var layout = codecs[c];
    var enc = new StringBuilder();
    var dec = new StringBuilder();
    for(int i = 0; i < layout.Count; ++i)
    {
      var f = layout[i];
      var slot = "dv." + codec_slots[i];
      var kw = f.Type.Keyword;
      if(kw == "bool")
      {
        enc.Append($"    {slot} = v.{f.Name} ? 1 : 0;\n");
        dec.Append($"    v.{f.Name} = {slot} != 0;\n");
      }
      else if(kw == "long" || kw == "ulong")
      {
        //NOTE: a double doesn't keep all the 64 bits of a number, its bits are kept instead
        enc.Append($"    {slot} = System.BitConverter.Int64BitsToDouble((long)v.{f.Name});\n");
        dec.Append($"    v.{f.Name} = ({kw})System.BitConverter.DoubleToInt64Bits({slot});\n");
      }
      else
      {
        enc.Append($"    {slot} = (double)v.{f.Name};\n");
        dec.Append($"    v.{f.Name} = ({f.Type.Text}){slot};\n");
      }
    }
    sb.Append($"  public static void Encode(ref this Val dv, {cs} v)\n  {{\n    dv.type = Types_{Id(c.Name)}.Value;\n{enc}  }}\n\n");
    sb.Append($"  public static void Decode(this Val dv, ref {cs} v)\n  {{\n{dec}  }}\n\n");
    sb.Append($"  public static Val ToVal(this {cs} v)\n  {{\n    var dv = new Val();\n    dv.Encode(v);\n    return dv;\n  }}\n");
  }

  Names CollectNames(Config conf)
  {
    var n = new Names();
    foreach(var owner in conf.AllIncludes().Prepend(conf))
    {
      foreach(var c in decls.Classes.Where(c => owners[c.Pos.File] == owner))
      {
        var cs = c.NativeType.Name;
        var full = FullName(c.NativeType);
        if(n.full_type_names.TryGetValue(full, out var same))
        {
          if(same.conf == owner && same.name != c.Name)
            throw new GenException(c.Pos, $"'{full}' is named '{same.name}' by another class, the class names it '{c.Name}'");
          //NOTE: named by a nearer config
          continue;
        }
        n.full_type_names[full] = (c.Name, owner);
        if(n.type_names.TryGetValue(cs, out var other) && other != c.Name)
        {
          if(cs == "IType" || !full.Contains("."))
            throw new GenException(c.Pos, $"'{cs}' is named '{other}' by another class or BHL itself, the class names it '{c.Name}'");
          n.ambiguous_names.Add(cs);
          continue;
        }
        n.type_names[cs] = c.Name;
      }
    }
    return n;
  }

  TypeRef Resolve(TypeDecl t, bool is_return, bool is_coro = false, bool is_field = false, string bhl_type = null)
  {
    //NOTE: [BhlType("Name")], e.g. a C# IList as the IList class rather than []any; a custom_rw one is still kept in Val
    if(bhl_type != null)
      return new TypeRef { Kind = t.Name != null && custom_rw.Contains(t.Name) ? Kind.CustomRW : Kind.Obj, Cs = t.Text, Bhl = bhl_type };
    if(t.Keyword != null)
    {
      if(t.Keyword == "void" && is_return)
        return new TypeRef { Kind = Kind.Void, Cs = t.Keyword, Bhl = "void" };
      if(builtins.TryGetValue(t.Keyword, out var bhl))
        return new TypeRef { Kind = Kind.Builtin, Cs = t.Keyword, Bhl = bhl };
    }
    else if(t.TupleItems != null && is_return)
    {
      return new TypeRef { Kind = Kind.Tuple, Cs = t.Text, Items = t.TupleItems.Select(i => Resolve(i, false)).ToList() };
    }
    else if(t.Name == "IList" && t.GenericArgs == null)
    {
      return new TypeRef { Kind = Kind.AnyArr, Cs = t.Text, Bhl = "any" };
    }
    else if((t.Name == "IList" || (is_field && t.Name == "List")) && t.GenericArgs?.Count == 1)
    {
      var item = Resolve(t.GenericArgs[0], false);
      if(item.Kind != Kind.Any && item.Kind != Kind.Arr && item.Kind != Kind.AnyArr)
        return new TypeRef { Kind = Kind.Arr, Cs = t.Text, Items = new List<TypeRef> { item },
          Proxy = "List_" + (item.Kind == Kind.Builtin ? meta_names[item.Cs] : Id(item.Bhl)),
          ProxyField = $"{cur.register_class}.t_List_" + (item.Kind == Kind.Builtin ? meta_names[item.Cs] : Id(item.Bhl)) };
    }
    else if(t.Name == "Action" || (t.Name == "Func" && t.GenericArgs != null))
    {
      var sig = (t.GenericArgs ?? new List<TypeDecl>()).Select(a => Resolve(a, false)).ToList();
      var ret = void_type;
      if(t.Name == "Func")
      {
        ret = sig[sig.Count - 1];
        sig.RemoveAt(sig.Count - 1);
      }
      return new TypeRef { Kind = Kind.Func, Cs = "VM.FuncPtr", Items = sig, Ret = ret, IsCoro = is_coro };
    }
    else if(t.Name != null && t.GenericArgs == null)
    {
      var kind = t.Name == "Val" ? Kind.Any : custom_rw.Contains(t.Name) ? Kind.CustomRW : decls.Enums.Contains(t.Name) ? Kind.Enum : Kind.Obj;
      var n = names[cur];
      string bhl_name;
      if(n.full_type_names.TryGetValue(FullName(t), out var named))
        bhl_name = named.name;
      else
      {
        if(n.ambiguous_names.Contains(t.Name))
          throw new GenException(t.Pos, $"type '{t.Text}' is ambiguous, native types of different namespaces are named '{t.Name}': qualify it");
        if(kind == Kind.Obj && !n.type_names.ContainsKey(t.Name) && !Declared(t.Name))
          throw new GenException(t.Pos, $"type '{t.Text}' is declared neither by a [BhlClass] nor in the sources: a generated one not generated yet, or a missing source dir?");
        bhl_name = n.type_names.TryGetValue(t.Name, out var short_name) ? short_name : t.Name;
      }
      return new TypeRef { Kind = kind, Cs = t.Text, Bhl = kind == Kind.Any ? "any" : bhl_name };
    }
    throw new GenException(t.Pos, $"type '{t.Text}' is not supported");
  }

  static string FullName(TypeDecl t)
  {
    return t.Text.StartsWith("global::") ? t.Text.Substring(8) : t.Text;
  }

  //NOTE: a type which isn't a [BhlClass] (bound elsewhere, e.g. by meta) is declared in the sources: a missing one, e.g.
  //      an enum of a generated source not generated yet, would be bound as a class silently. The text is searched
  //      rather than parsed, the sources are parsed only when they may have bindings
  bool Declared(string name)
  {
    if(!declared.TryGetValue(name, out var found))
    {
      var re = new System.Text.RegularExpressions.Regex($@"\b(class|struct|interface|record)\s+{name}\b");
      found = sources.Any(s => s.src.Contains(name) && re.IsMatch(s.src));
      declared[name] = found;
    }
    return found;
  }

  static string TypeRefCode(TypeRef t)
  {
    if(t.Kind == Kind.Tuple)
      return "types.TTuple(" + string.Join(",", t.Items.Select(TypeRefCode)) + ")";
    if(t.Kind == Kind.Arr)
      return "types.TArr(" + TypeRefCode(t.Items[0]) + ")";
    if(t.Kind == Kind.AnyArr)
      return "types.TArr(types.T(\"any\"))";
    if(t.Kind == Kind.Func)
      return $"types.TFunc({(t.IsCoro ? "true" : "false")}, {TypeRefCode(t.Ret)}" + string.Concat(t.Items.Select(i => ", " + TypeRefCode(i))) + ")";
    return $"types.T(\"{t.Bhl}\")";
  }

  const string Conv = "global::UnityBHL.BindConv.";

  //NOTE: the native value by a BindConv rule, op is "To" (src is a Val) or "Pop" (src is the exec);
  //      null for a plain value, read from a field of the Val by the generated code itself
  static string ConvExpr(TypeRef t, string op, string src)
  {
    switch(t.Kind)
    {
      case Kind.Any:
        return $"{Conv}{op}Any({src})";
      case Kind.Arr:
        return $"{Conv}{op}List<{t.Items[0].Cs}>({src}, {t.ProxyField})";
      case Kind.AnyArr:
        return $"{Conv}{op}AnyList({src})";
      case Kind.Func:
        return $"{Conv}{op}Func({src})";
      default:
        return null;
    }
  }

  //NOTE: the native value of a Val, null for a custom_rw type, it's read by its Decode(..)
  static string Val2NativeExpr(TypeRef t, string val)
  {
    switch(t.Kind)
    {
      case Kind.Builtin:
        switch(t.Cs)
        {
          case "double": return $"{val}.num";
          case "string": return $"{val}.str";
          case "bool": return $"{val}.bval";
          default: return $"({t.Cs}){val}.num";
        }
      case Kind.Enum:
        return $"({t.Cs})((int){val}.num)";
      case Kind.CustomRW:
        return null;
      default:
        return ConvExpr(t, "To", val) ?? $"({t.Cs}){val}.obj";
    }
  }

  static string Val2Native(TypeRef t, string val, string native)
  {
    if(t.Kind == Kind.CustomRW)
      return $"{val}.Decode(ref {native});";
    return $"{native} = {Val2NativeExpr(t, val)};";
  }

  static string Native2Val(TypeRef t, string native, string val)
  {
    switch(t.Kind)
    {
      case Kind.Builtin:
        if(t.IsFloat)
          return $"{val}.SetFlt({native});";
        if(t.Cs == "string")
          return $"{val}.SetStr({native});";
        if(t.Cs == "bool")
          return $"{val}.SetBool({native});";
        return $"{val}.SetInt({native});";
      case Kind.Any:
      case Kind.Func:
        return $"{val}.SetObj({native}, Types.Any);";
      case Kind.Enum:
        return $"{val}.SetInt((int){native});";
      case Kind.CustomRW:
        return $"{val}.Encode({native});";
      //NOTE: a native function returning its array argument gives BHL its own array back
      case Kind.Arr:
        return $"{t.ProxyField}.SetList(ref {val}, {native});";
      default:
        return $"{val}.SetObjNoRefc({native}, Types_{Id(t.Bhl)}.Value);";
    }
  }

  //NOTE: pushes the native return value(s) onto the stack
  static void ReturnVal(StringBuilder sb, TypeRef t, string var, string indent)
  {
    if(t.Kind == Kind.Tuple)
    {
      //NOTE: items are pushed from the last one
      for(int i = t.Items.Count; i-- > 0;)
        sb.Append($"{indent}{{ var dv{i} = new Val(); {Native2Val(t.Items[i], var + ".Item" + (i + 1), "dv" + i)} exec.stack.Push(dv{i}); }}\n");
    }
    else if(t.Kind == Kind.Any)
      sb.Append($"{indent}exec.stack.Push({var});\n");
    else if(t.Kind == Kind.Builtin)
    {
      if(t.IsFloat)
        sb.Append($"{indent}exec.stack.Push((double){var});\n");
      else if(t.Cs == "string" || t.Cs == "bool")
        sb.Append($"{indent}exec.stack.Push(({t.Cs}){var});\n");
      else
        sb.Append($"{indent}exec.stack.Push(Val.NewInt((double){var}));\n");
    }
    else
      sb.Append($"{indent}{{ var dv = new Val(); {Native2Val(t, var, "dv")} exec.stack.Push(dv); }}\n");
  }

  static string DisposeArg(TypeRef t, string v)
  {
    switch(t.Kind)
    {
      case Kind.Any:
        return $"{v}._refc?.Release(); {v} = default;";
      case Kind.Arr:
      case Kind.AnyArr:
        return $"{{ if({v} is IRefcounted rfc) rfc.Release(); {v} = default; }}";
      case Kind.Func:
        return $"{v}?.Release(); {v} = default;";
      default:
        return null;
    }
  }

  class Func
  {
    public MethodDecl Decl;
    public List<(string name, TypeRef type, string def)> Args;
    public TypeRef Ret;
    //NOTE: returns a BhlTask form (BitGames.BhlTask of UnityBHL), bound as a coroutine, Ret is its result
    public bool IsTask;

    public bool IsCoroutine => Decl.IsCoroutine || IsTask;
    //NOTE: a first VM parameter gets the VM running the call (exec.vm), a first VM.ExecState one the call's
    //      exec; it's not a BHL argument. Null if none
    public string PassVm;

    public string Name => Decl.BhlName ?? Decl.Name;
    public bool HasArgs => Args.Count > 0;
    public bool HasDisposableArgs => Args.Any(a => DisposeArg(a.type, "") != null);
    //NOTE: a builtin or any returned by a non coroutine is pushed directly, others by the generated ReturnValue(..)
    public bool HasReturnValue => Ret.Kind != Kind.Void && (IsCoroutine || (Ret.Kind != Kind.Builtin && Ret.Kind != Kind.Any));
    public List<TypeRef> RetItems => Ret.Kind == Kind.Void ? new List<TypeRef>() : Ret.Kind == Kind.Tuple ? Ret.Items : new List<TypeRef> { Ret };
  }

  static bool IsVm(TypeDecl t)
  {
    return t.Name == "VM" && t.GenericArgs == null && (t.Text == "VM" || t.Text == "bhl.VM") || IsExec(t);
  }

  static bool IsExec(TypeDecl t)
  {
    return t.Name == "ExecState" && (t.Text == "VM.ExecState" || t.Text == "bhl.VM.ExecState");
  }

  TypeRef ResolveParam(ParamDecl p)
  {
    if(p.BhlTypeOf == null)
      return Resolve(p.Type, false, p.IsCoroutine, bhl_type: p.BhlType);
    var t = Resolve(p.BhlTypeOf, false, p.IsCoroutine);
    if(t.Kind != Kind.Func || p.Type.Name != "FuncPtr")
      throw new GenException(p.Pos, "[BhlType(typeof(T))] is expected on a VM.FuncPtr parameter, T a func type (Action, Func<..>)");
    return t;
  }

  Func ResolveFunc(MethodDecl m)
  {
    foreach(var p in m.Params)
    {
      if(p.Modifiers != "")
        throw new GenException(p.Pos, $"parameter modifier '{p.Modifiers}' is not supported");
    }
    if(m.IsCoroutine && m.CoroClass == null)
      throw new GenException(m.Pos, $"a coroutine is bound as a BhlTask function or a [BhlCoroutine] class, '{m.Name}' is neither");
    var task_result = TaskResult(m.ReturnType);
    //NOTE: as @bhl_pass_vm of metagen_bhl_bind, after self of a class method (not among Params)
    bool pass_vm = m.Params.Count > 0 && IsVm(m.Params[0].Type);
    if(pass_vm && m.CoroClass != null)
      throw new GenException(m.Params[0].Pos, "a [BhlCoroutine] class has exec itself, its Init can't take a VM or VM.ExecState argument");
    var f = new Func {
      Decl = m,
      PassVm = !pass_vm ? null : IsExec(m.Params[0].Type) ? "exec" : "exec.vm",
      Args = m.Params.Skip(pass_vm ? 1 : 0).Select(p => (name: p.Name, type: ResolveParam(p), def: p.Default)).ToList(),
      IsTask = task_result != null,
      Ret = task_result == null ? Resolve(m.ReturnType, true, bhl_type: m.ReturnBhlType) : task_result == no_result ? void_type : Resolve(task_result, true, bhl_type: m.ReturnBhlType),
    };
    if(f.IsTask)
    {
      //NOTE: the coroutine outlives the call of the method, the args would be released while the task still uses them
      foreach(var a in f.Args.Where(a => DisposeArg(a.type, "") != null))
        throw new GenException(m.Params.First(p => p.Name == a.name).Pos, $"a BhlTask coroutine can't take '{a.type.Cs}' yet: the arg would be released before the task completes");
    }
    foreach(var p in m.Params.Where(p => p.IsCoroutine))
    {
      if(f.Args.First(a => a.name == p.Name).type.Kind != Kind.Func)
        throw new GenException(p.Pos, "[BhlCoroutine] is expected on a func-typed parameter");
    }
    if(f.RetItems.Any(i => i.Kind == Kind.AnyArr || i.Kind == Kind.Func))
      throw new GenException(m.ReturnType.Pos, $"returning '{m.ReturnType.Text}' is not supported");
    return f;
  }

  class Class
  {
    public ClassDecl Decl;
    public TypeRef Self;
    public List<(FieldDecl decl, TypeRef type)> Fields;
    public List<Func> Methods;
  }

  Class ResolveClass(ClassDecl c)
  {
    var cl = new Class {
      Decl = c,
      Self = new TypeRef { Kind = c.CustomRW ? Kind.CustomRW : Kind.Obj, Cs = c.NativeType.Text, Bhl = c.Name, IsPod = c.Pod },
      Fields = c.Fields.Select(f => (f, Resolve(f.Type, false, is_field: true, bhl_type: f.BhlType))).ToList(),
      Methods = c.Methods.Select(ResolveFunc).ToList(),
    };
    foreach(var f in cl.Fields)
    {
      if(f.type.Kind == Kind.AnyArr || f.type.Kind == Kind.Func)
        throw new GenException(f.decl.Pos, $"a field of type '{f.decl.Type.Text}' is not supported");
    }
    return cl;
  }

  //NOTE: a part of the output: the functions and classes of one declarations file, or a slice of them
  class Slice
  {
    public string Name;
    public List<Class> Classes = new List<Class>();
    public List<Func> Funcs = new List<Func>();
    public int Count => Classes.Count + Funcs.Count;
  }

  //NOTE: the output files by their names
  //NOTE: the output of the config being emitted (cur), the funcs and classes of its sources
  Dictionary<string, string> Emit(out int funcs_count, out int classes_count)
  {
    var resolved = funcs.Where(f => owners[f.decl_file] == cur).Select(f => (f: ResolveFunc(f.m), f.decl_file)).ToList();
    var classes = decls.Classes.Where(c => owners[c.Pos.File] == cur).Select(ResolveClass).ToList();
    funcs_count = resolved.Count;
    classes_count = classes.Count;
    var all_funcs = resolved.Select(r => r.f).Concat(classes.SelectMany(c => c.Methods)).ToList();
    //NOTE: the native list types of the array args, returns and fields, by name in the order of use
    var proxies = new Dictionary<string, TypeRef>();
    var arr_types = all_funcs.SelectMany(f => f.Args.Select(a => a.type).Concat(f.RetItems))
      .Concat(classes.SelectMany(c => c.Fields.Select(f => f.type)));
    foreach(var t in arr_types)
    {
      if(t.Kind == Kind.Arr && !proxies.ContainsKey(t.Proxy))
        proxies.Add(t.Proxy, t.Items[0]);
    }

    //NOTE: the files the output is made of, the Unity editor regenerates it when one of them changes
    var deps = decl_files.Where(f => owners[f] == cur)
      .Concat(all_funcs.Select(f => f.Decl.Pos.File))
      .Concat(classes.SelectMany(c => c.Decl.Fields.Select(f => f.Pos.File)))
      .Select(f => Path.GetRelativePath(cur.Dir, f).Replace('\\', '/'))
      .Distinct()
      .OrderBy(f => f, System.StringComparer.Ordinal);

    var slices = MakeSlices(classes, resolved, cur.Dir);
    var files = new Dictionary<string, string>();
    foreach(var slice in slices)
      files.Add(slice.Name + ".cs", EmitSlice(slice));

    var sb = new StringBuilder();
    sb.Append(Header + "\n");
    foreach(var d in deps)
      sb.Append($"//dep: {d}\n");
    EmitFileBegin(sb);
    if(proxies.Count > 0)
    {
      sb.Append("#if !BHL_FRONT\n");
      foreach(var kv in proxies)
        sb.Append($"internal static NativeListTypeSymbol<{kv.Value.Native}> t_{kv.Key};\n");
      sb.Append("#endif\n\n");
    }

    //NOTE: as BHL_AutoBindings of metagen_bhl_bind: all RegisterBegin(..) go before all RegisterEnd(..),
    //      which set up the classes once all the types are defined
    sb.Append("public static void RegisterBegin(Types types)\n{\n");
    foreach(var kv in proxies)
      EmitProxy(sb, kv.Key, kv.Value);
    foreach(var slice in slices)
      sb.Append($"  Register_{slice.Name}(types);\n");
    sb.Append("}\n\n");

    sb.Append("public static void RegisterEnd(Types types)\n{\n");
    foreach(var c in classes)
    {
      sb.Append("#if !BHL_FRONT\n");
      sb.Append($"  Types_{Id(c.Decl.Name)}.Value = SetupType(types, \"{c.Decl.Name}\");\n");
      sb.Append("#else\n");
      sb.Append($"  types.SetupType(\"{c.Decl.Name}\");\n");
      sb.Append("#endif\n");
    }
    sb.Append("}\n\n");

    if(classes.Count > 0)
    {
      sb.Append("#if !BHL_FRONT\n");
      sb.Append("static IType SetupType(Types types, string name)\n{\n");
      sb.Append("  var tmp = types.T(name).Get();\n");
      sb.Append("  if(tmp == null)\n    throw new System.Exception(\"Type '\" + name + \"' not resolved\");\n");
      sb.Append("  if(tmp is ClassSymbolNative csn)\n    csn.Setup();\n");
      sb.Append("  else if(tmp is InterfaceSymbolNative isn)\n    isn.Setup();\n");
      sb.Append("  return tmp;\n}\n");
      sb.Append("#endif\n\n");
    }
    sb.Append("}\n\n");

    if(classes.Count > 0)
    {
      //NOTE: the same holders as metagen_bhl_bind declares, the code it generates refers to them
      sb.Append("#if !BHL_FRONT\n");
      //NOTE: ToVal makes the Val of a native value typed as the class, FromVal is the native value of a Val
      foreach(var c in classes)
      {
        var cs = c.Decl.NativeType.Text;
        sb.Append($"static public class Types_{Id(c.Decl.Name)} {{\n  static public IType Value;\n");
        if(c.Decl.CustomRW)
        {
          sb.Append($"  static public Val ToVal({cs} v) {{ var dv = new Val(); dv.Encode(v); return dv; }}\n");
          sb.Append($"  static public {cs} FromVal(Val v) {{ {cs} r = default; v.Decode(ref r); return r; }}\n");
        }
        else
        {
          sb.Append($"  static public Val ToVal({cs} o) => Val.NewObj(o, Value);\n");
          sb.Append($"  static public {cs} FromVal(Val v) => ({cs})v.obj;\n");
        }
        sb.Append("}\n");
      }
      sb.Append("#endif\n\n");
    }
    var auto_codecs = classes.Where(c => c.Decl.AutoCodec).ToList();
    if(auto_codecs.Count > 0)
    {
      sb.Append("#if !BHL_FRONT\n");
      sb.Append($"public static class {cur.register_class}_Codecs\n{{\n");
      for(int i = 0; i < auto_codecs.Count; ++i)
      {
        if(i > 0)
          sb.Append("\n");
        EmitCodec(sb, auto_codecs[i].Decl);
      }
      sb.Append("}\n");
      sb.Append("#endif\n\n");
    }
    sb.Append("}\n");
    files.Add(MainFile, sb.ToString());
    return files;
  }

  //NOTE: by declarations file in the order of the files, split into slices of SliceSize; named after the file,
  //      files of the same name (sources with [BhlBind] methods in different dirs) after their paths from conf_dir
  static List<Slice> MakeSlices(List<Class> classes, List<(Func f, string decl_file)> funcs, string conf_dir)
  {
    var by_file = new SortedDictionary<string, Slice>(System.StringComparer.Ordinal);
    Slice Of(string file)
    {
      if(!by_file.TryGetValue(file, out var s))
        by_file[file] = s = new Slice();
      return s;
    }
    foreach(var c in classes)
      Of(c.Decl.Pos.File).Classes.Add(c);
    foreach(var (f, file) in funcs)
      Of(file).Funcs.Add(f);

    string Sanitize(string s) => System.Text.RegularExpressions.Regex.Replace(s, @"\W", "_");
    var same_names = by_file.Keys.GroupBy(f => Sanitize(Path.GetFileNameWithoutExtension(f)))
      .Where(g => g.Count() > 1).SelectMany(g => g).ToHashSet();

    var slices = new List<Slice>();
    var names = new Dictionary<string, string>();
    foreach(var kv in by_file)
    {
      var name = !same_names.Contains(kv.Key) ? Sanitize(Path.GetFileNameWithoutExtension(kv.Key)) :
        Sanitize(Path.ChangeExtension(Path.GetRelativePath(conf_dir, kv.Key), null).Replace("..", "up"));
      if(names.TryGetValue(name, out var other))
        throw new GenException($"files '{other}' and '{kv.Key}' make outputs of the same name '{name}'");
      names.Add(name, kv.Key);

      var all = kv.Value;
      int count = (all.Count + SliceSize - 1) / SliceSize;
      for(int i = 0; i < count; ++i)
      {
        var slice = new Slice { Name = count == 1 ? name : $"{name}_{i}" };
        //NOTE: classes first, as in the declarations
        var units = all.Classes.Cast<object>().Concat(all.Funcs).Skip(i * SliceSize).Take(SliceSize);
        foreach(var u in units)
        {
          if(u is Class c)
            slice.Classes.Add(c);
          else
            slice.Funcs.Add((Func)u);
        }
        slices.Add(slice);
      }
    }
    return slices;
  }

  void EmitFileBegin(StringBuilder sb)
  {
    sb.Append("#pragma warning disable CS0162\n");
    sb.Append("#pragma warning disable UDR0001\n\n");
    foreach(var u in header_usings)
      sb.Append($"using {u};\n");
    sb.Append("#if !BHL_FRONT\n");
    //NOTE: the namespaces of the included outputs have the Types_<Class> of their classes
    foreach(var imp in cur.imports.Concat(imports[cur]).Concat(cur.AllIncludes().Select(i => i.@namespace)).Except(header_usings).Except(new[] { cur.@namespace }).Distinct())
      sb.Append($"using {imp};\n");
    sb.Append("#endif\n");
    sb.Append("using Types = bhl.Types;\n\n");
    sb.Append($"namespace {cur.@namespace} {{\n\n");
    sb.Append($"static public partial class {cur.register_class} {{\n\n");
  }

  string EmitSlice(Slice slice)
  {
    var sb = new StringBuilder();
    sb.Append(Header + "\n");
    EmitFileBegin(sb);
    sb.Append($"public static void Register_{slice.Name}(Types types)\n{{\n");
    foreach(var c in slice.Classes)
      EmitClass(sb, c);
    foreach(var f in slice.Funcs)
      EmitFunc(sb, f, "fn_" + Id(f.Name), NsScope("types.ns", f.Name), f.Decl.CoroClass != null ? null : $"{f.Decl.Target}.{f.Decl.Name}", null, false);
    sb.Append("}\n\n}\n\n");

    //NOTE: the generated parts of the [BhlCoroutine] classes
    var coros = slice.Funcs.Where(f => f.Decl.CoroClass != null).ToList();
    if(coros.Count > 0)
    {
      sb.Append("#if !BHL_FRONT\n\n");
      foreach(var f in coros)
        EmitPartial(sb, f);
      sb.Append("#endif\n\n");
    }
    sb.Append("}\n");
    return sb.ToString();
  }

  //NOTE: the BHL names of types as a list of ProxyType, null if none
  static string ProxyTypes(List<string> names)
  {
    return names.Count == 0 ? "null" : "new List<ProxyType>() { " + string.Join(", ", names.Select(n => $"types.T(\"{n}\")")) + " }";
  }

  void EmitClass(StringBuilder sb, Class c)
  {
    if(c.Decl.IsInterface)
    {
      EmitInterface(sb, c);
      return;
    }
    //NOTE: name as a part of C# identifiers
    var name = Id(c.Decl.Name);
    var native = c.Self.Cs;
    sb.Append("  {\n");
    if(c.Decl.New)
    {
      sb.Append($"    static void ctor_{name}(VM.ExecState exec, ref Val v, IType type)\n    {{\n");
      sb.Append("    #if !BHL_FRONT\n");
      sb.Append($"      var o = new {native}();\n");
      sb.Append(c.Decl.CustomRW ? "      v.Encode(o);\n" : "      v.SetObjNoRefc(o, type);\n");
      sb.Append("    #endif\n    }\n\n");
    }
    sb.Append($"    var cl = new ClassSymbolNative(new Origin(), \"{ShortName(c.Decl.Name)}\",\n");
    sb.Append(c.Decl.Parent != null ? $"      types.T(\"{c.Decl.Parent}\"),\n" : "      new ProxyType(),\n");
    sb.Append($"      proxy_implements: {ProxyTypes(c.Decl.Implements)},\n");
    sb.Append($"      creator: {(c.Decl.New ? "ctor_" + name : "null")}\n");
    sb.Append("      #if !BHL_FRONT\n");
    sb.Append($"      , native_type: typeof({native})\n");
    if(c.Decl.CustomRW)
      sb.Append($"      , native_object_getter: (v) => {{ {native} tmp = default; v.Decode(ref tmp); return tmp; }}\n");
    sb.Append("      #endif\n");
    sb.Append("    );\n");
    sb.Append($"    {NsScope("types.ns", c.Decl.Name)}.Define(cl);\n\n");

    foreach(var (f, t) in c.Fields)
    {
      var member = "f." + (f.Native ?? f.Name);
      sb.Append("    {\n");
      if(f.Get)
      {
        sb.Append($"      static void get_{name}_{f.Name}(VM.ExecState exec, Val ctx, ref Val v, FieldSymbol fld)\n      {{\n");
        sb.Append("      #if !BHL_FRONT\n");
        //NOTE: as metagen_bhl_bind: a Pod one is read in place
        if(c.Decl.CustomRW)
          sb.Append($"        {native} f = default; ctx.Decode(ref f);\n");
        else if(c.Decl.Pod)
          sb.Append($"        ref var f = ref System.Runtime.CompilerServices.Unsafe.Unbox<{native}>(ctx.obj);\n");
        else
          sb.Append($"        var f = ({native})ctx.obj;\n");
        sb.Append($"        {Native2Val(t, member, "v")}\n");
        sb.Append("      #endif\n      }\n");
      }
      if(f.Set)
      {
        sb.Append($"      static void set_{name}_{f.Name}(VM.ExecState exec, ref Val ctx, Val v, FieldSymbol fld)\n      {{\n");
        sb.Append("      #if !BHL_FRONT\n");
        if(c.Decl.CustomRW)
          sb.Append($"        {native} f = default; ctx.Decode(ref f);\n");
        else
          sb.Append($"        var f = ({native})ctx.obj;\n");
        //NOTE: Decode(..) needs a variable, not a property
        if(t.Kind == Kind.CustomRW)
          sb.Append($"        {{ {t.Native} tmp = default; {Val2Native(t, "v", "tmp")} {member} = tmp; }}\n");
        //NOTE: as metagen_bhl_bind: the BHL array is copied into the native list, a new one if there's none
        else if(t.Kind == Kind.Arr)
          sb.Append($"        {{ var tmp = {member}; {t.ProxyField}.CopyTo(v, ref tmp); {member} = tmp; }}\n");
        else
          sb.Append($"        {Val2Native(t, "v", member)}\n");
        //NOTE: a value type is changed in a copy, it's written back
        if(c.Decl.CustomRW)
          sb.Append("        ctx.Encode(f);\n");
        else if(c.Decl.Pod)
          sb.Append("        ctx.obj = f; //copy on write\n");
        sb.Append("      #endif\n      }\n");
      }
      sb.Append($"      cl.Define(new FieldSymbol(new Origin(), \"{f.Name}\", {TypeRefCode(t)}, {(f.Get ? $"get_{name}_{f.Name}" : "null")}, {(f.Set ? $"set_{name}_{f.Name}" : "null")}));\n");
      sb.Append("    }\n");
    }

    foreach(var m in c.Methods)
    {
      bool self_arg = m.Decl.SelfArgType != null;
      //NOTE: a static one is called on the native type, it has no self
      if(m.Decl.IsStatic)
      {
        var callee = m.Decl.HasBody ? $"{m.Decl.Target}.{m.Decl.Name}" : $"{native}.{m.Decl.Native ?? m.Decl.Name}";
        EmitFunc(sb, m, name + "_" + m.Name, "cl", callee, null, false, is_static: true);
        //NOTE: also as the operator, as @bhl_bin_op of metagen_bhl_bind binds it additionally to the method
        if(m.Decl.Op != null)
          EmitFunc(sb, m, name + "_" + m.Name + "_op", "cl", callee, null, false, is_static: true, bhl_name: m.Decl.Op);
      }
      else
        EmitFunc(sb, m, name + "_" + m.Name, "cl", m.Decl.HasBody ? $"{m.Decl.Target}.{m.Decl.Name}" : self_arg ? $"{m.Decl.Target}.{name}_{m.Name}" : "__self." + (m.Decl.Native ?? m.Name), c.Self, self_arg);
    }
    sb.Append("  }\n");
  }

  //NOTE: as metagen_bhl_bind binds an interface: its methods are called on the object as the native interface
  void EmitInterface(StringBuilder sb, Class c)
  {
    var name = Id(c.Decl.Name);
    sb.Append("  {\n");
    sb.Append("    var funcs = new List<FuncSymbol>();\n");
    foreach(var m in c.Methods)
      EmitFunc(sb, m, name + "_" + m.Name, "funcs", "__self." + (m.Decl.Native ?? m.Name), c.Self, false, add: true);
    sb.Append($"    var ifs = new InterfaceSymbolNative(new Origin(), \"{ShortName(c.Decl.Name)}\", {ProxyTypes(c.Decl.Inherits)},\n");
    sb.Append("      #if !BHL_FRONT\n");
    sb.Append($"      typeof({c.Self.Cs}),\n");
    sb.Append("      #else\n      null,\n      #endif\n");
    sb.Append("      funcs.ToArray()\n    );\n");
    sb.Append($"    {NsScope("types.ns", c.Decl.Name)}.Define(ifs);\n");
    sb.Append("  }\n");
  }

  //NOTE: the same native list type as metagen_bhl_bind defines, whichever registers first defines it
  static void EmitProxy(StringBuilder sb, string name, TypeRef item)
  {
    sb.Append("#if !BHL_FRONT\n");
    sb.Append($"  t_{name} = NativeListTypeSymbol.DefineOnce<{item.Native}>(types.ns, \"{name}\",\n");
    var v2n = Val2NativeExpr(item, "v");
    if(v2n != null)
      sb.Append($"    (v) => {v2n},\n");
    else
      sb.Append($"    (v) => {{ {item.Native} tmp = default; {Val2Native(item, "v", "tmp")} return tmp; }},\n");
    sb.Append($"    (itype, n) => {{ var v = new Val(); {Native2Val(item, "n", "v")} return v; }},\n");
    sb.Append($"    {TypeRefCode(item)});\n");
    sb.Append("#else\n");
    sb.Append($"  NativeListTypeSymbol.DefineOnce(types.ns, \"{name}\", {TypeRefCode(item)});\n");
    sb.Append("#endif\n");
  }

  //NOTE: args are popped in reverse order, a default one only when it was passed
  static void ReadArgs(StringBuilder sb, Func f, string prefix, string indent)
  {
    int defaults = f.Args.Count(a => a.def != null);
    int default_counter = 0;
    for(int i = f.Args.Count; i-- > 0;)
    {
      var a = f.Args[i];
      if(a.def != null)
      {
        ++default_counter;
        sb.Append($"{indent}if(!args_info.IsDefaultArgUsed({defaults - default_counter}))\n");
      }
      var pop = ConvExpr(a.type, "Pop", "exec");
      if(pop != null)
        sb.Append($"{indent}{prefix}{a.name} = {pop};\n");
      else
        sb.Append($"{indent}{{ var dv = exec.stack.Pop(); {Val2Native(a.type, "dv", prefix + a.name)} dv._refc?.Release(); }}\n");
      if(a.def != null)
        sb.Append($"{indent}else\n{indent}  {prefix}{a.name} = {a.def};\n");
    }
  }

  //NOTE: callee is null for a [BhlCoroutine] class; self is the class of a method, passed to the callee first if self_arg;
  //      is_static for a static class method; bhl_name if it's not f.Name (an operator); add: scope is a list
  //      of the funcs (of an interface) rather than a scope to define it in
  void EmitFunc(StringBuilder sb, Func f, string local_fn, string scope, string callee, TypeRef self, bool self_arg, bool is_static = false, string bhl_name = null, bool add = false)
  {
    sb.Append("  {\n");
    sb.Append("    #if !BHL_FRONT\n");
    sb.Append($"    static bhl.Coroutine {local_fn}(VM.ExecState exec, FuncArgsInfo args_info)\n    {{\n");
    if(f.Decl.CoroClass != null)
      EmitCoroCall(sb, f);
    else
      EmitDirectCall(sb, f, callee, self, self_arg);
    sb.Append("    }\n");
    sb.Append("    #endif\n\n");

    var attrib = (f.IsCoroutine ? "FuncAttrib.Coro" : "FuncAttrib.None") + (is_static ? " | FuncAttrib.Static" : "");
    sb.Append($"    var fn = new FuncSymbolNative(new Origin(), \"{ShortName(bhl_name ?? f.Name)}\", {attrib}, {TypeRefCode(f.Ret)}, {f.Args.Count(a => a.def != null)},\n");
    sb.Append("      #if !BHL_FRONT\n");
    sb.Append($"      {local_fn}\n");
    sb.Append("      #else\n      null\n      #endif\n");
    foreach(var a in f.Args)
      sb.Append($"      , new FuncArgSymbol(\"{a.name}\", {TypeRefCode(a.type)}, false)\n");
    sb.Append("    );\n");
    sb.Append($"    {scope}.{(add ? "Add" : "Define")}(fn);\n");
    sb.Append("  }\n");
  }

  static void EmitDirectCall(StringBuilder sb, Func f, string callee, TypeRef self, bool self_arg)
  {
    if(self != null)
    {
      sb.Append("      ref var dv_self = ref exec.GetSelfRef();\n");
      sb.Append($"      {self.Native} __self = default;\n");
      sb.Append($"      {Val2Native(self, "dv_self", "__self")}\n");
    }
    foreach(var a in f.Args)
      sb.Append($"      {a.type.Native} __{a.name} = default;\n");
    ReadArgs(sb, f, "__", "      ");
    if(self != null)
      sb.Append("      exec.stack.Pop(); //pop self\n");
    var call_args = f.Args.Select(a => "__" + a.name);
    if(f.PassVm != null)
      call_args = call_args.Prepend(f.PassVm);
    if(self_arg)
      call_args = call_args.Prepend("__self");
    //NOTE: an operator method calls the C# operator of the native type
    var call = f.Decl.Op != null ? string.Join($" {f.Decl.Op} ", call_args) : $"{callee}({string.Join(", ", call_args)})";
    if(f.IsTask)
    {
      EmitTaskCall(sb, f, call, self);
      return;
    }
    sb.Append("      ");
    if(f.Ret.Kind != Kind.Void)
      sb.Append("var return_val = ");
    sb.Append($"{call};\n");
    if(self != null)
      sb.Append($"      {SelfDone(self)}\n");
    if(f.Ret.Kind != Kind.Void)
      ReturnVal(sb, f.Ret, "return_val", "      ");
    foreach(var a in f.Args)
    {
      var dispose = DisposeArg(a.type, "__" + a.name);
      if(dispose != null)
        sb.Append($"      {dispose}\n");
    }
    sb.Append("      return null;\n");
  }

  //NOTE: as metagen_bhl_bind binds a direct @bhl_coroutine: the scope makes the task live as long as the call,
  //      the result is pushed when the task completes
  //NOTE: as metagen_bhl_bind: a value type self is written back, the method may have changed it,
  //      a reference one is released
  static string SelfDone(TypeRef self)
  {
    if(self.Kind == Kind.CustomRW)
      return "dv_self.Encode(__self);";
    if(self.IsPod)
      return "dv_self.obj = __self; //copy on write";
    return "dv_self._refc?.Release();";
  }

  static void EmitTaskCall(StringBuilder sb, Func f, string call, TypeRef self)
  {
    sb.Append("      var scope = global::BitGames.BHL.BhlTaskScope.Enter();\n");
    sb.Append("      try\n      {\n");
    sb.Append($"        var task = {call};\n");
    if(self != null)
      sb.Append($"        {SelfDone(self)}\n");
    sb.Append("        return global::BitGames.BHL.BhlTaskCoroutine.New(exec, scope, task");
    if(f.Ret.Kind != Kind.Void)
    {
      sb.Append(", static (exec, return_val) =>\n        {\n");
      ReturnVal(sb, f.Ret, "return_val", "          ");
      sb.Append("        }");
    }
    sb.Append(");\n");
    sb.Append("      }\n      finally\n      {\n        scope.Exit();\n      }\n");
  }

  //NOTE: Exec and Cleanup of a [BhlCoroutine] class take exec (void Cleanup(VM.ExecState exec)) or nothing
  //      (void Cleanup()), the latter is callable from C# without a VM
  static bool TakesExec(MethodDecl m, string name)
  {
    if(m.ReturnType.Text == "void" && m.Params.Count == 1 && IsExec(m.Params[0].Type))
      return true;
    if(m.ReturnType.Text == "void" && m.Params.Count == 0)
      return false;
    throw new GenException(m.Pos, $"expected void {name}(VM.ExecState exec) or void {name}()");
  }

  //NOTE: Exec of a [BhlCoroutine] class: void Exec(VM.ExecState exec) sets exec.status itself, bool Exec() returns
  //      true while running, its results are out parameters (bool Exec(out T result)) set by the last call
  static string CoroExecCall(Func f)
  {
    var m = f.Decl.CoroExec;
    var n = f.RetItems.Count;
    if(m.Params.Count == 1 && m.ReturnType.Text == "void" && IsExec(m.Params[0].Type))
      return "Exec(exec);";
    if(m.ReturnType.Text != "bool" || m.Params.Count != n || m.Params.Any(p => p.Modifiers != "out"))
      throw new GenException(m.Pos, $"expected void Exec(VM.ExecState exec) or bool Exec({string.Join(", ", f.RetItems.Select((t, i) => $"out {t.Native} r{i}"))})");
    var outs = string.Join(", ", Enumerable.Range(0, n).Select(i => $"out var r{i}"));
    var ret = n == 0 ? "" : $"\n    else\n      ReturnValue(exec, {string.Join(", ", Enumerable.Range(0, n).Select(i => "r" + i))});";
    return $"if(Exec({outs}))\n      exec.status = BHS.RUNNING;{ret}";
  }

  //NOTE: starts the [BhlCoroutine] class
  static void EmitCoroCall(StringBuilder sb, Func f)
  {
    sb.Append($"      var coro = CoroutinePool.New<{f.Decl.CoroClass}>(exec.vm);\n");
    sb.Append("      coro.Init(exec, args_info);\n");
    sb.Append("      return coro;\n");
  }

  //NOTE: the generated part of a [BhlCoroutine] class: its args read and passed to its Init(exec, ..); with a disposable
  //      one (a func) they're a field living as long as the coroutine, released when it ends, else locals
  static void EmitPartial(StringBuilder sb, Func f)
  {
    sb.Append($"public partial class {f.Decl.CoroClass} : bhl.Coroutine\n{{\n");

    //NOTE: a field only for the disposable args, else they're the locals of Init
    bool args_field = f.HasArgs && f.HasDisposableArgs;
    if(args_field)
    {
      sb.Append("  struct Args : IDisposable\n  {\n");
      foreach(var a in f.Args)
        sb.Append($"    public {a.type.Native} {a.name};\n");
      sb.Append("\n    public void Dispose()\n    {\n");
      foreach(var a in f.Args)
      {
        var dispose = DisposeArg(a.type, a.name);
        if(dispose != null)
          sb.Append($"      {dispose}\n");
      }
      sb.Append("    }\n");
      sb.Append("  }\n\n");
      sb.Append("  Args args;\n\n");
    }

    if(f.HasReturnValue)
    {
      sb.Append($"  static public void ReturnValue(VM.ExecState exec{string.Concat(f.RetItems.Select((t, i) => $", {t.Native} v{i}"))})\n  {{\n");
      //NOTE: items are pushed from the last one
      for(int i = f.RetItems.Count; i-- > 0;)
        sb.Append($"    {{ var dv{i} = new Val(); {Native2Val(f.RetItems[i], "v" + i, "dv" + i)} exec.stack.Push(dv{i}); }}\n");
      sb.Append("  }\n\n");
    }

    var prefix = args_field ? "args." : "__";
    sb.Append("  public void Init(VM.ExecState exec, FuncArgsInfo args_info)\n  {\n");
    if(!args_field)
    {
      foreach(var a in f.Args)
        sb.Append($"    {a.type.Native} __{a.name} = default;\n");
    }
    ReadArgs(sb, f, prefix, "    ");
    sb.Append($"    Init({string.Join(", ", (f.Decl.CoroInitExec ? new[] { "exec" } : new string[0]).Concat(f.Args.Select(a => prefix + a.name)))});\n  }}\n\n");
    sb.Append($"  public override void Tick(VM.ExecState exec)\n  {{\n    {CoroExecCall(f)}\n  }}\n\n");
    sb.Append($"  public override void Destruct(VM.ExecState exec)\n  {{\n    Cleanup({(TakesExec(f.Decl.CoroCleanup, "Cleanup") ? "exec" : "")});\n");
    if(args_field)
      sb.Append("    args.Dispose();\n    args = default;\n");
    sb.Append("  }\n}\n\n");
  }
