using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

internal class Generator
{
  //NOTE: the config and the ones it includes, the included ones first: one model, an output per config
  readonly List<Config> confs;
  readonly ICsParser parser;
  readonly CsDecls decls = new CsDecls();
  //NOTE: with the declarations file binding it, the output is split by them
  readonly List<(MethodDecl m, string decl_file)> funcs = new List<(MethodDecl, string)>();
  //NOTE: the config of a source file, the first one listing it (an included one before the including one)
  readonly Dictionary<string, Config> owners = new Dictionary<string, Config>();
  readonly Dictionary<Config, List<string>> imports = new Dictionary<Config, List<string>>();
  //NOTE: the BHL names of the native types as a config sees them: a native type may be named by classes of several
  //      configs (as meta allowed), a config uses its own one, else the one of the nearest config it includes
  class Names
  {
    //NOTE: named otherwise: by a [BhlClass], or BHL's own (bhl.IType is Type); a type not listed is named as in C#
    public readonly Dictionary<string, string> type_names = new Dictionary<string, string> { ["IType"] = "Type" };
    //NOTE: by the qualified native type, with the config naming it; a short name of native types of different
    //      namespaces is ambiguous, such a type is qualified where it's used
    public readonly Dictionary<string, (string name, Config conf)> full_type_names = new Dictionary<string, (string, Config)>();
    public readonly HashSet<string> ambiguous_names = new HashSet<string>();
  }
  readonly Dictionary<Config, Names> names = new Dictionary<Config, Names>();
  //NOTE: custom_rw: of all the configs
  readonly HashSet<string> custom_rw = new HashSet<string>();
  //NOTE: the layouts of the AutoCodec classes, a property per Val number
  readonly Dictionary<ClassDecl, List<FieldDecl>> codecs = new Dictionary<ClassDecl, List<FieldDecl>>();
  static readonly string[] codec_slots = { "num", "_num2", "_num3", "_num4" };
  static readonly HashSet<string> codec_keywords = new HashSet<string> { "bool", "byte", "sbyte", "short", "ushort", "int", "uint", "long", "ulong", "float", "double" };
  //NOTE: the config being emitted, its register class holds the native list types of its output
  Config cur;
  //NOTE: the sources with declarations ([BhlClass], [BhlInterface], [BhlCoroutine] classes, [BhlBind(typeof(T), ..)])
  readonly List<string> decl_files = new List<string>();
  //NOTE: all the sources, a type bound elsewhere (meta) must be declared in them, see Declared
  List<(string file, string src)> sources;
  readonly Dictionary<string, bool> declared = new Dictionary<string, bool>();

  static readonly System.Text.RegularExpressions.Regex decl_attrs = new System.Text.RegularExpressions.Regex(@"BhlClass|BhlInterface|BhlCoroutine|BhlBind\s*\(\s*typeof");

  static bool IsDeclFile(string src) => decl_attrs.IsMatch(src);

  static readonly string[] header_usings = { "System", "System.Collections", "System.Collections.Generic", "bhl" };

  //NOTE: a BHL name may be in a namespace, 'LM3.Chip': the symbol is the last part defined in the namespaces of the
  //      rest (Nest), a C# identifier made of it has '_' for '.' as metagen_bhl_bind names them (Types_LM3_Chip)
  static readonly System.Text.RegularExpressions.Regex bhl_name = new System.Text.RegularExpressions.Regex(@"^[A-Za-z_]\w*(\.[A-Za-z_]\w*)*$");

  static string Id(string name) => name.Replace('.', '_');

  static string ShortName(string name) => name.Substring(name.LastIndexOf('.') + 1);

  static string NsScope(string root, string name)
  {
    var parts = name.Split('.');
    return root + string.Concat(parts.Take(parts.Length - 1).Select(p => $".Nest(\"{p}\")"));
  }

  static void CheckName(string name, SrcPos pos)
  {
    if(!bhl_name.IsMatch(name))
      throw new GenException(pos, $"'{name}' isn't a BHL name, identifiers separated by '.'");
  }

  //NOTE: the binary operators BHL may overload, the same in C#
  static readonly string[] bin_ops = { "+", "-", "*", "/", "%", "==", "!=", "<", ">", "<=", ">=" };


  //NOTE: the max of functions and classes in one output file, as metagen_bhl_bind slices its output:
  //      IL2CPP has troubles with too large files and methods
  const int SliceSize = 20;
  public const string MainFile = "register.cs";
  public const string Header = "//THIS FILE IS GENERATED by UnityBHL bindgen, do not edit";

  public Generator(List<Config> confs, ICsParser parser)
  {
    this.confs = confs;
    this.parser = parser;
    foreach(var conf in confs)
    {
      if(confs.Any(c => c != conf && c.result_dir == conf.result_dir))
        throw new GenException($"{conf.FilePath}: 'result_dir' is another config's too");
      custom_rw.UnionWith(conf.custom_rw);
      imports[conf] = new List<string>();
    }
  }

  //NOTE: generates and writes the output of each config, returns the summary and whether a file was written or deleted
  public (string summary, bool changed) Run()
  {
    Collect();
    var summary = new List<string>();
    bool changed = false;
    foreach(var conf in confs)
    {
      cur = conf;
      var files = Emit(out int funcs_count, out int classes_count);

      Directory.CreateDirectory(conf.result_dir);
      int written = files.Count(kv => WriteIfChanged(Path.Combine(conf.result_dir, kv.Key), kv.Value));
      //NOTE: only the generated files, recognized by the header, anything else in the dir is left as is
      int deleted = 0;
      foreach(var file in Directory.GetFiles(conf.result_dir, "*.cs"))
      {
        if(files.ContainsKey(Path.GetFileName(file)) || File.ReadLines(file).FirstOrDefault() != Header)
          continue;
        File.Delete(file);
        ++deleted;
      }
      summary.Add($"bindgen: {funcs_count} funcs, {classes_count} classes -> {conf.result_dir} ({files.Count} files, {written} written, {deleted} deleted)");
      changed |= written + deleted > 0;
    }
    return (string.Join("\n", summary), changed);
  }

  //NOTE: an unchanged output isn't touched, so neither Unity nor the BHL compiler rebuild anything
  static bool WriteIfChanged(string path, string content)
  {
    if(File.Exists(path) && File.ReadAllText(path) == content)
      return false;
    File.WriteAllText(path, content);
    return true;
  }

  void Collect()
  {
    //NOTE: the declarations are in the sources too, in the files with the attributes making them
    foreach(var conf in confs)
    {
      foreach(var file in conf.SourceFiles.Where(f => !owners.ContainsKey(f)))
        owners.Add(file, conf);
    }
    sources = owners.Keys.Select(f => (file: f, src: File.ReadAllText(f))).ToList();
    foreach(var (file, src) in sources.Where(s => IsDeclFile(s.src)))
    {
      decl_files.Add(file);
      parser.ParseDecls(file, src, decls);
    }

    ApplyDeclsNamespaces();

    //NOTE: a class names its native type in BHL, for its config and the ones including it
    foreach(var conf in confs)
      names[conf] = CollectNames(conf);

    var types = new HashSet<string>(decls.Binds.Select(b => b.Type).Concat(decls.BindAlls.Select(b => b.Type)));
    //NOTE: an AutoCodec one's native fields are checked against its layout when the type is in the sources
    foreach(var c in decls.Classes.Where(c => c.AutoCodec))
      types.Add(c.NativeType.Name);
    foreach(var c in decls.Classes.Where(c => c.MemberRefs.Count > 0))
    {
      types.Add(c.NativeType.Name);
      types.UnionWith(c.MemberRefs.Where(r => r.Type != null).Select(r => r.Type));
    }
    foreach(var (file, src) in sources)
    {
      //NOTE: parsing only the files which may declare enums, bound types or [BhlBind] methods
      if(!src.Contains("enum ") && !src.Contains("BhlBind") && !types.Any(t => src.Contains("class " + t) || src.Contains("struct " + t) || src.Contains("interface " + t)))
        continue;
      parser.ParseSource(file, src, types, decls);
    }

    foreach(var all in decls.BindAlls)
      decls.Binds.AddRange(BindAll(all));

    //NOTE: by the BHL name, a method may be bound by [BhlBind] on it and in a declarations file
    var seen = new Dictionary<string, SrcPos>();
    foreach(var b in decls.Binds)
    {
      //NOTE: one of a declarations file is in the BHL namespace of its C# one (decls_namespace)
      var decl_ns = b.BhlName == null ? BhlNs(b.Pos.File, b.DeclNs) : null;
      var bhl_name = b.BhlName ?? (decl_ns != null ? decl_ns + "." + b.Name : b.Name);
      CheckName(bhl_name, b.Pos);
      if(seen.TryGetValue(bhl_name, out var other))
        throw new GenException(b.Pos, $"'{bhl_name}' is bound twice, also at {other}");
      seen.Add(bhl_name, b.Pos);
      if(!decls.Methods.TryGetValue((b.Type, b.Name), out var found) || !found[0].IsStatic)
        throw new GenException(b.Pos, $"static method '{b.Type}.{b.Name}' is not found in the sources");
      if(found.Count > 1)
        throw new GenException(found[1].Pos, $"'{b.Type}.{b.Name}' is overloaded, BHL has no overloads");
      if(found[0].IsGeneric)
        throw new GenException(found[0].Pos, $"'{b.Type}.{b.Name}' is generic, it can't be bound");
      AddFunc(bhl_name == found[0].Name ? found[0] : found[0].WithBhlName(bhl_name), b.Pos.File);
    }

    foreach(var c in decls.Coroutines)
    {
      //NOTE: the generated part of a [BhlCoroutine] class is in the namespace of the output
      if(c.DeclNs != owners[c.Pos.File].@namespace)
        throw new GenException(c.Pos, $"[BhlCoroutine] class '{c.CoroClass}' is expected in namespace '{owners[c.Pos.File].@namespace}'");
      var bhl_name = c.BhlName ?? c.Name;
      if(seen.TryGetValue(bhl_name, out var other))
        throw new GenException(c.Pos, $"'{bhl_name}' is bound twice, also at {other}");
      seen.Add(bhl_name, c.Pos);
      AddFunc(c, c.Pos.File);
    }

    ResolveBases();

    var seen_classes = new HashSet<string>();
    foreach(var c in decls.Classes)
    {
      CheckName(c.Name, c.Pos);
      if(!seen_classes.Add(c.Name))
        throw new GenException(c.Pos, $"class '{c.Name}' is bound twice");
      if(c.Pod && c.CustomRW)
        throw new GenException(c.Pos, $"class '{c.Name}' is either Pod or CustomRW");
      //NOTE: its args and returns are marshalled by Encode/Decode too, as the custom_rw of the config
      if(c.CustomRW)
        custom_rw.Add(c.NativeType.Name);
      if(c.AutoCodec)
        codecs[c] = CheckAutoCodec(c);
      if(c.IsInterface && (c.Parent != null || c.New || c.Pod || c.CustomRW || c.Fields.Count > 0 || c.MemberRefs.Count > 0 || c.Implements.Count > 0))
        throw new GenException(c.Pos, $"interface '{c.Name}' has only methods and Inherits");
      if(!c.IsInterface && c.Inherits.Count > 0)
        throw new GenException(c.Pos, $"class '{c.Name}' implements interfaces by Implements, Inherits is an interface's");
      //NOTE: as BHL calls an interface method on the object, whichever class it is
      foreach(var m in c.Methods.Where(m => c.IsInterface && (m.IsStatic || m.HasBody)))
        throw new GenException(m.Pos, $"interface method '{c.Name}.{m.Name}' can't be static or have a body");
      AddImports(owners[c.Pos.File], c.Usings);
      foreach(var r in c.MemberRefs)
        AddMember(c, r);
      foreach(var m in c.Methods)
      {
        //NOTE: a static method with a body of the declaration itself: of the native type first a method on it (self),
        //      else a static one
        if(m.HasBody)
        {
          if(m.Op != null || m.Native != null)
            throw new GenException(m.Pos, "a method with a body can't be an operator or have [BhlNative]");
          m.Target = "global::" + (c.Ns != null ? c.Ns + "." : "") + c.DeclName;
          if(!m.IsStatic && m.Params.Count > 0 && m.Params[0].Type.Name == c.NativeType.Name)
          {
            m.Params = m.Params.Skip(1).ToList();
            m.SelfArgType = c.DeclName;
          }
          else
            m.IsStatic = true;
          continue;
        }
        //NOTE: as BHL wants an operator overload: static, of two arguments, returning a value
        if(m.Op != null && !bin_ops.Contains(m.Op))
          throw new GenException(m.Pos, $"operator '{m.Op}' is not one of {string.Join(" ", bin_ops)}");
        if(m.Op != null && (m.Params.Count != 2 || IsVm(m.Params[0].Type) || m.ReturnType.Keyword == "void" || TaskResult(m.ReturnType) != null))
          throw new GenException(m.Pos, $"operator '{m.Op}' is expected to take two arguments and return a value");
        if(m.SelfArgType == null)
          continue;
        //NOTE: as metagen_bhl_bind binds a method without its own native prefix
        var name = Id(c.Name) + "_" + m.Name;
        if(!decls.Methods.TryGetValue((m.SelfArgType, name), out var found) || !found[0].IsStatic)
          throw new GenException(m.Pos, $"static method '{m.SelfArgType}.{name}' is not found in the sources");
        m.Target = found[0].Target;
        AddImports(owners[c.Pos.File], found[0].Usings);
      }
    }
  }

  //NOTE: the C# bases of a declaration are declarations too: of a class the parent class and the implemented
  //      interfaces, of an interface the inherited ones; the types declared elsewhere are named by Parent,
  //      Implements, Inherits
  void ResolveBases()
  {
    var by_decl = decls.Classes.GroupBy(c => c.DeclName).ToDictionary(g => g.Key, g => g.ToList());
    foreach(var c in decls.Classes)
    {
      foreach(var b in c.Bases)
      {
        var base_decl = FindBase(by_decl, c, b);
        if(base_decl == null)
          throw new GenException(c.Pos, $"base '{b}' of '{c.DeclName}' isn't a [BhlClass] or [BhlInterface] declaration, a type declared elsewhere is named by Parent, Implements or Inherits");
        if(c.IsInterface && !base_decl.IsInterface)
          throw new GenException(c.Pos, $"interface '{c.Name}' can't inherit class '{base_decl.Name}'");
        if(c.IsInterface)
          c.Inherits.Add(base_decl.Name);
        else if(base_decl.IsInterface)
          c.Implements.Add(base_decl.Name);
        else if(c.Parent != null)
          throw new GenException(c.Pos, $"class '{c.Name}' has one parent, '{c.Parent}' and '{base_decl.Name}' are given");
        else
          c.Parent = base_decl.Name;
      }
    }
  }

  //NOTE: the declaration a base names, of the same name in several namespaces the one C# finds: of the namespace of
  //      the declaration or the closest enclosing one
  static ClassDecl FindBase(Dictionary<string, List<ClassDecl>> by_decl, ClassDecl c, string b)
  {
    if(!by_decl.TryGetValue(b, out var list))
      return null;
    if(list.Count == 1)
      return list[0];
    for(var ns = c.Ns; ; ns = ns.Contains('.') ? ns.Substring(0, ns.LastIndexOf('.')) : null)
    {
      var found = list.Where(d => d.Ns == ns).ToList();
      if(found.Count == 1)
        return found[0];
      if(ns == null)
        throw new GenException(c.Pos, $"base '{b}' of '{c.DeclName}' is ambiguous, qualify the declarations by their namespaces");
    }
  }

  //NOTE: decls_namespace of the config of the file: the BHL namespace of a declaration in a C# namespace under it
  string BhlNs(string file, string cs_ns)
  {
    var root = owners[file].decls_namespace;
    if(string.IsNullOrEmpty(root) || cs_ns == null || !cs_ns.StartsWith(root + "."))
      return null;
    return cs_ns.Substring(root.Length + 1);
  }

  //NOTE: the classes, interfaces and custom functions named by their declarations (not by an explicit name)
  //      in the BHL namespaces of their C# ones
  void ApplyDeclsNamespaces()
  {
    foreach(var c in decls.Classes.Where(c => !c.NameGiven))
    {
      var ns = BhlNs(c.Pos.File, c.Ns);
      if(ns != null)
        c.Name = ns + "." + c.Name;
    }
  }

  //NOTE: a member of the native type itself, or a static <Type>.<Class>_<Method>(self, ..) of another one
  void AddMember(ClassDecl c, MemberRef r)
  {
    var native = c.NativeType.Name;
    if(r.Type == null || r.Type == native)
    {
      if(decls.Fields.TryGetValue((native, r.Name), out var field))
      {
        c.Fields.Add(field);
        AddImports(owners[c.Pos.File], field.Usings);
        return;
      }
      if(!decls.Methods.TryGetValue((native, r.Name), out var found))
        throw new GenException(r.Pos, $"member '{native}.{r.Name}' is not found in the sources");
      if(found.Count > 1)
        throw new GenException(found[1].Pos, $"'{native}.{r.Name}' is overloaded, BHL has no overloads");
      c.Methods.Add(found[0]);
      AddImports(owners[c.Pos.File], found[0].Usings);
      return;
    }

    var prefix = Id(c.Name) + "_";
    if(!r.Name.StartsWith(prefix))
      throw new GenException(r.Pos, $"'{r.Type}.{r.Name}' is expected to be named {prefix}<Method>");
    if(!decls.Methods.TryGetValue((r.Type, r.Name), out var self_arg) || !self_arg[0].IsStatic)
      throw new GenException(r.Pos, $"static method '{r.Type}.{r.Name}' is not found in the sources");
    if(self_arg.Count > 1)
      throw new GenException(self_arg[1].Pos, $"'{r.Type}.{r.Name}' is overloaded, BHL has no overloads");
    var m = self_arg[0];
    if(m.Params.Count == 0 || m.Params[0].Type.Name != native)
      throw new GenException(m.Pos, $"the first parameter of '{r.Type}.{r.Name}' is expected to be {native} self");
    //NOTE: a copy, the same method may be bound by other declarations
    c.Methods.Add(new MethodDecl {
      Name = r.Name.Substring(prefix.Length),
      SelfArgType = r.Type,
      ReturnType = m.ReturnType,
      ReturnBhlType = m.ReturnBhlType,
      Params = m.Params.Skip(1).ToList(),
      Usings = m.Usings,
      Pos = m.Pos,
    });
  }

  void AddImports(Config owner, List<string> usings)
  {
    foreach(var u in usings)
    {
      if(!header_usings.Contains(u) && !imports[owner].Contains(u))
        imports[owner].Add(u);
    }
  }

  //NOTE: the static methods of the type in the order of the sources, each bound at the position of the
  //      declaration; a method which can't be bound fails the generation, Except leaves it out
  //      shortcut: a new file with methods of the type isn't a dep of the output, the editor regenerates
  //      on the next change of a dep
  List<BindDecl> BindAll(BindAllDecl all)
  {
    var statics = decls.Methods.Where(kv => kv.Key.type == all.Type && kv.Value.Any(m => m.IsStatic)).Select(kv => kv.Key.name).ToList();
    if(statics.Count == 0)
      throw new GenException(all.Pos, $"no static methods of '{all.Type}' are found in the sources");
    foreach(var e in all.Except.Where(e => !statics.Contains(e.Name)))
      throw new GenException(e.Pos, $"static method '{all.Type}.{e.Name}' is not found in the sources");
    return statics.Where(name => !all.Except.Any(e => e.Name == name))
      .Select(name => new BindDecl { Type = all.Type, Name = name, DeclNs = all.DeclNs, Pos = all.Pos }).ToList();
  }

  void AddFunc(MethodDecl m, string decl_file)
  {
    funcs.Add((m, decl_file));
    //NOTE: the signatures are written as in their files, so the output imports their usings
    AddImports(owners[decl_file], m.Usings);
  }

  enum Kind
  {
    Void,
    Builtin,
    Any,
    Enum,
    Obj,
    CustomRW,
    Tuple,
    //NOTE: IList<T>, Items[0] is T
    Arr,
    //NOTE: IList, BHL []any
    AnyArr,
    //NOTE: Action<..> or Func<..>, Items are the args
    Func,
  }

  class TypeRef
  {
    public Kind Kind;
    //NOTE: the C# type as written in the source (a keyword for builtins)
    public string Cs;
    public string Bhl;
    public List<TypeRef> Items;
    //NOTE: the name of the native list type of an Arr, named as metagen_bhl_bind does
    public string Proxy;
    //NOTE: the field holding the native list type of an Arr
    public string ProxyField;
    //NOTE: the return type of a Func
    public TypeRef Ret;
    //NOTE: a coroutine Func
    public bool IsCoro;
    //NOTE: the self of a Pod class, a boxed value type
    public bool IsPod;

    //NOTE: the type of a C# variable holding the value
    public string Native => Kind == Kind.Any ? "bhl.Val" : Cs;

    public bool IsFloat => Cs == "float" || Cs == "double";
  }

